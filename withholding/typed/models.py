class TemplateSpec(_Frozen):
    """One registry entry: how a family's prompts are rendered and read (design 2.1). The DERIVED fields
    (accepted_kwargs, think_open_in_prompt, the template_* channels, answer_channel, role_names, no_tools_marker) are
    computed by the registry loader from its probes and checked here (invariants 1 to 5); invariants 6 to 8 (render and
    delivery probes) are the loader's. ``spec_id`` is computed over the identity fields and can never be passed."""

    model_pattern: str
    subfolder_pattern: str | None
    template_from: str
    template_revision: str
    template_sha: str
    tokenizer_from: str
    tokenizer_subfolder: str | None
    tokenizer_revision: str
    accepted_kwargs: frozenset[str]
    kwargs: dict[str, bool]
    generation_prefix_text: str
    generation_prefix_ids: tuple[int, ...]
    think_open_in_prompt: bool
    reasoning_channel: ReasoningChannel
    answer_channel: AnswerChannel
    trained_answer_channel: TrainedChannel
    open_marker: str
    close_marker: str
    open_ids: tuple[int, ...]
    close_ids: tuple[int, ...]
    special_ids: dict[str, int | None]
    stop_ids: tuple[int, ...]
    trained_stop_strings: tuple[str, ...]
    role_names: tuple[str, ...]
    turn_start_ids: tuple[int, ...]
    bos: BosPolicy
    tool_slot: Literal["tools_kwarg", "system_functions_field", "none"]
    no_tools_marker: str | None
    default_system_line: str | None
    trained_decoding: dict[str, float] | None
    citations: dict[str, Citation]

    @model_validator(mode="after")
    def _invariants(self) -> TemplateSpec:
        _hex(self.template_sha, HEX64, "template_sha")
        for name in ("template_revision", "tokenizer_revision"):  # invariant 4: commit shas, never "main" (R12)
            _hex(getattr(self, name), HEX40, name)
        _need(bool(self.open_marker) and bool(self.close_marker) and self.open_marker != self.close_marker,
              "open and close markers are distinct and non-empty")
        _need(bool(self.open_ids) and bool(self.close_ids), "open_ids and close_ids may not be empty")
        # invariant 1: think_open_in_prompt holds exactly when the prefix ids end with the open ids
        _need(self.think_open_in_prompt == _ends_with(self.generation_prefix_ids, self.open_ids),
              "think_open_in_prompt must equal 'generation_prefix_ids ends with open_ids' (invariant 1)")
        _need((self.reasoning_channel == "template_opens") == self.think_open_in_prompt,
              "reasoning_channel is template_opens exactly when the prefix opens the block (invariant 1)")
        _need((self.reasoning_channel == "template_closed") == self.prefix_closes_block,
              "reasoning_channel is template_closed exactly when the prefix ends with a closed block (invariant 1)")
        # invariant 2: the answer channel is rule D's for the reasoning channel; any other value is refused
        _need(self.answer_channel == RULE_D_CHANNEL[self.reasoning_channel],
              f"answer_channel must be {RULE_D_CHANNEL[self.reasoning_channel]} under rule D for "
              f"{self.reasoning_channel} (invariant 2)")
        # invariant 3: kwargs are a subset of the derived accepted kwargs
        extra = set(self.kwargs) - set(self.accepted_kwargs)
        _need(not extra, f"kwargs {sorted(extra)} are not read by the template (invariant 3; audit 28)")
        # invariant 5: each declared fact has a citation
        missing = TEMPLATE_SPEC_CITED - set(self.citations)
        _need(not missing, f"citations missing for {sorted(missing)} (invariant 5)")
        unknown = set(self.citations) - set(type(self).model_fields) - {"template"}
