def split_sections(text: str) -> list[tuple[str, int, str]]:
    """The level-2 sections of a markdown text: (heading line without its line ending, 1-based line number, body).
    The body is every line after the heading, line endings kept, up to the next level-1 or level-2 heading or the end;
    a ``#`` line inside a fenced block is not a heading. A SectionCitation pins this body's ``section_sha``."""
    out: list[tuple[str, int, list[str]]] = []
    fence = False
    current: list[str] | None = None
    for i, line in enumerate(text.splitlines(keepends=True), 1):
        if line.lstrip().startswith("```"):
            fence = not fence
        if not fence and line.startswith("## "):
            current = []
            out.append((line.rstrip("\r\n"), i, current))
        elif not fence and line.startswith("# "):
            current = None
        elif current is not None:
            current.append(line)
    return [(h, n, "".join(body)) for h, n, body in out]


_split_sections = split_sections  # the name registry.py reads (added to the partial file by the registry builder)


class SectionCitation(_Frozen):
    """A record of a note cited by its heading and the ``section_sha`` of the text under it (design 2.8). The heading
    must occur exactly once; ``line_hint`` is printed only and never used to resolve."""

    path: str
    heading: str
    content_sha: str
    line_hint: int | None = None

    @model_validator(mode="after")
    def _shape(self) -> SectionCitation:
        _hex(self.content_sha, HEX64, "content_sha")
        _need(self.heading.startswith("## "), "heading must be the markdown level-2 heading line")
        return self

    def verify(self, text: str | None = None) -> None:
        """Re-read the file (or ``text``): the heading occurs once and the ``section_sha`` of the text under it is
        ``content_sha``; RegistryError naming the heading otherwise."""
        body = resolve_heading(Path(self.path).read_text(encoding="utf-8") if text is None else text, self.heading,
                               self.path)
        if section_sha(body) != self.content_sha:
            raise RegistryError(f"{self.path}: the text under {self.heading!r} moved from its pinned sha")


def resolve_heading(text: str, heading: str, path: str = "<text>") -> str:
    """The body under ``heading``; RegistryError unless it occurs exactly once."""
    hits = [body for h, _, body in split_sections(text) if h == heading]
    if len(hits) != 1:
        raise RegistryError(f"{path}: heading {heading!r} occurs {len(hits)} times, not once")
    return hits[0]


