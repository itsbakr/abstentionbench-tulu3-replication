def _ends_with(seq: tuple[int, ...], tail: tuple[int, ...]) -> bool:
    return bool(tail) and len(seq) >= len(tail) and seq[-len(tail):] == tail


def _find(seq: tuple[int, ...], sub: tuple[int, ...], start: int = 0) -> int:
    """Index of the first occurrence of ``sub`` in ``seq`` at or after ``start``, or -1."""
    n = len(sub)
    for i in range(start, len(seq) - n + 1):
        if seq[i:i + n] == sub:
            return i
    return -1


