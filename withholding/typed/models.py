    def counts(self) -> dict[str, Any]:
        """n, n_rows, the scorer, spec, verdict-view, generation-config and dataset sets, undelivered by reason,
        unparsed by reason, the flag counts (2.2, 2.3, 2.4, section 9) and the modes."""
        a = self._analysis()
        keep = ("n", "n_rows", "scorer_ids", "spec_ids", "verdict_views", "generation_config_ids", "datasets",
                "undelivered", "unparsed", "excluded_unparsed_n", "kept_n", "cut_at_cap_n", "cut_at_inner_open_n",
                "blocks_removed_n",
                "tool_render_legacy_n", "tokenizer_revision_not_recorded_n", "prefix_parity_failed_n",
                "max_model_len_not_recorded_n", "modes")
        return {k: a[k] for k in keep}

    def worst_case(self) -> tuple[float, float] | None:
        """The bracket of every censored row at both ends (computed in every view, for the quoting rule)."""
        return self._analysis()["worst_case"]

    def label_suffix(self) -> str:
        """`` (<rule label>; <record>)`` beside a sensitivity number; empty for a primary cell (design 2.7)."""
        a = self._analysis()
        return "" if a["column"] == "primary" else f" ({rule_label(a['read_rule'])}; {', '.join(a['owner_decisions'])})"

    def quote(self, prereg: PreregRule | None = None) -> str:
        """D7 with D18 on a level: the point only when the preregistered label is the same at both ends of the
        worst-case bracket, read as points (a level carries no interval here; a level the prereg labels nowhere is
        ``not_registered`` at both ends, so it prints as a point), otherwise the bracket with no point; ``pending`` and
        ``not_bracketable`` print no number. A delta's quote adds each end's own interval (DeltaCell.verdict)."""
        a = self._analysis()
        if a["status"] != "ok" or a["worst_case"] is None:
            return a["status"] if a["status"] != "ok" else "not_computed"
        lo, hi = a["worst_case"]
        same = prereg_label(prereg, lo) == prereg_label(prereg, hi)
        if same and a["estimate"] is not None:
            return f"{a['estimate']:.3f}{self.label_suffix()}"
        return f"[{lo:.3f}, {hi:.3f}]{self.label_suffix()}"

    def render(self) -> str:
        """The number as its view prints it, with the rule and record beside a sensitivity number."""
        a = self._analysis()
        if a["status"] != "ok":
            return a["status"]
        if a["bracket"] is not None:
            return f"[{a['bracket'][0]:.3f}, {a['bracket'][1]:.3f}]{self.label_suffix()}"
        return ("n/a" if a["estimate"] is None else f"{a['estimate']:.3f}") + self.label_suffix()


