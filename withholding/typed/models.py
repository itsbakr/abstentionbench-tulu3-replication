class CoordinateScheme(_Frozen):
    """The coordinates a cell may carry and a ``cell:`` grant line may name (design 2.7, 2.8): for each key, the
    allowed values, or a pattern every value must match in full."""

    values: dict[str, tuple[str, ...]]
    patterns: dict[str, str] = {}

    @model_validator(mode="after")
    def _keys(self) -> CoordinateScheme:
        _need(not set(self.values) & set(self.patterns), "a coordinate key has either values or a pattern")
        for p in self.patterns.values():
            re.compile(p)
        return self

    def check(self, coords: Mapping[str, str]) -> None:
        """ValueError for an unknown key or a value the scheme does not hold."""
        canonical_coordinates(coords)
        for k, v in coords.items():
            if k in self.values:
                _need(v in self.values[k], f"coordinate {k}={v} is not registered")
            elif k in self.patterns:
                _need(re.fullmatch(self.patterns[k], v) is not None, f"coordinate {k}={v} does not match "
                                                                     f"{self.patterns[k]!r}")
            else:
                raise ValueError(f"coordinate key {k!r} is not registered")


