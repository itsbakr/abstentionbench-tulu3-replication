# ================================================================================================== rule ids (2.3)

CloseRule = Literal["first", "last"]
StrayRule = Literal["after_tag", "content"]
TurnRule = Literal["none", "cut_at_boundary", "cut_in_delivered"]
_SENS_NAME = re.compile(r"S_[A-Za-z0-9_]+")


class RuleD(_Frozen):
    """Rule D's parameters (design 2.3): the close rule (D2), the stray-close rule (D3), the invented-turn rule (D4:
    none = option c, cut_at_boundary = option a, cut_in_delivered = option b) and the named task overrides of the close
    rule (RLCR's ``rlcr.close``), at a rule date. The inner-open cut and D15's closed-block removal are content rules
    of every rule D id, so no parameter names them.

    ``rule_id`` is computed, never written by hand: ``D@<date>|close=<>|stray=<>|turn=<>`` then one
    ``|<family>.close=<value>`` per override, sorted by family. An override equal to the default close rule is
    refused, so each reading has exactly one canonical id."""

    date: date
    close: CloseRule
    stray: StrayRule
    turn: TurnRule
    overrides: tuple[tuple[Family, CloseRule], ...] = ()

    @model_validator(mode="after")
    def _overrides_canonical(self) -> RuleD:
        fams = [f for f, _ in self.overrides]
        _need(fams == sorted(set(fams)), "rule D overrides must be sorted by family, one per family")
        for f, v in self.overrides:
            _need(v != self.close, f"override {f}.close={v} equals the default close rule; it names nothing")
        return self

    @computed_field
    @property
    def rule_id(self) -> str:
        """The canonical id (design 2.3)."""
        base = f"D@{self.date.isoformat()}|close={self.close}|stray={self.stray}|turn={self.turn}"
        return base + "".join(f"|{f}.close={v}" for f, v in self.overrides)

    def close_for(self, family: str) -> CloseRule:
        """The close rule a row of ``family`` is split at: its override, else the default (D2)."""
        return dict(self.overrides).get(family, self.close)  # type: ignore[return-value]


def parse_rule_d(rule_id: str) -> RuleD:
    """The RuleD whose canonical id is exactly ``rule_id``; ValueError for anything else (a prefix, a reordering, a
    missing parameter, a redundant override, trailing text). 22 Oct 2026 (step 3): a parsed id is kept per process
    (`_parse_rule_d`): the RuleD is frozen and the parse a pure function of the string, and the registry's rule-id
    sets re-parse every registered id on each read (the step 3 profile spent half its typing time here)."""
    _need(isinstance(rule_id, str), f"a rule id is a str, got {type(rule_id).__name__}")
    return _parse_rule_d(rule_id)


@functools.cache
def _parse_rule_d(rule_id: str) -> RuleD:
    parts = rule_id.split("|")
    _need(len(parts) >= 4 and parts[0].startswith("D@"), f"not a rule D id: {rule_id!r}")
    try:
        d = date.fromisoformat(parts[0][2:])
    except ValueError as e:
        raise ValueError(f"not a rule D id (date): {rule_id!r}") from e
    vals = {}
    for key, part in zip(("close", "stray", "turn"), parts[1:4]):
        k, sep, v = part.partition("=")
        _need(sep == "=" and k == key, f"not a rule D id (expected {key}=...): {rule_id!r}")
        vals[key] = v
    overrides = []
    for part in parts[4:]:
        k, sep, v = part.partition("=")
        fam, dot, param = k.partition(".")
        _need(sep == "=" and dot == "." and param == "close", f"not a rule D override: {part!r} in {rule_id!r}")
        overrides.append((fam, v))
    rule = RuleD.model_validate({"date": d, "close": vals["close"], "stray": vals["stray"], "turn": vals["turn"],
                                 "overrides": tuple(overrides)})
    _need(rule.rule_id == rule_id, f"not the canonical form: {rule_id!r} (canonical {rule.rule_id!r})")
    return rule


def parse_sensitivity_id(rule_id: str) -> tuple[str, RuleD]:
    """(name, base) of a sensitivity id ``<name>@<rule D id>`` (design 2.3, Revision 3); ValueError when either part
    is not canonical. A bare name is not a sensitivity id. Kept per process, as parse_rule_d."""
    _need(isinstance(rule_id, str), f"a rule id is a str, got {type(rule_id).__name__}")
    return _parse_sensitivity_id(rule_id)


@functools.cache
def _parse_sensitivity_id(rule_id: str) -> tuple[str, RuleD]:
    name, sep, base = rule_id.partition("@")
    _need(sep == "@" and bool(_SENS_NAME.fullmatch(name)), f"not a sensitivity id: {rule_id!r}")
    return name, parse_rule_d(base)


def rule_kind(rule_id: str) -> Literal["rule_d", "sensitivity"]:
    """Whether ``rule_id`` is a canonical rule D id or a canonical sensitivity id over one; ValueError otherwise."""
    if isinstance(rule_id, str) and rule_id.startswith("D@"):
        parse_rule_d(rule_id)
        return "rule_d"
    parse_sensitivity_id(rule_id)
    return "sensitivity"


def rule_base(rule_id: str) -> str:
    """The rule D id a read rule reads under: itself for a rule D id, the base inside a sensitivity id."""
    return rule_id if rule_kind(rule_id) == "rule_d" else rule_id.partition("@")[2]


def rule_date(rule_id: str) -> date:
    """The rule date a read rule carries (the date of its rule D id)."""
    return parse_rule_d(rule_base(rule_id)).date


# The four rule D ids of design 2.3 ("The four rule D ids are step 2a's (OD-1), 2b's (D2), 2c's (D3) and 2d's (D4)"),
# used only to label a rule id in print; what is registered is read from the decisions note's grants
# (tests/typed/test_models.py checks that these are exactly the rule D ids the grants hold).
RULE_D_STEPS: tuple[tuple[str, RuleD], ...] = (
    ("2a", RuleD(date=STEP0_DATE, close="last", stray="after_tag", turn="none")),
    ("2b", RuleD(date=STEP0_DATE, close="first", stray="after_tag", turn="none", overrides=(("rlcr", "last"),))),
    ("2c", RuleD(date=STEP0_DATE, close="first", stray="content", turn="none", overrides=(("rlcr", "last"),))),
    ("post-2d", RuleD(date=STEP0_DATE, close="first", stray="content", turn="cut_at_boundary",
                      overrides=(("rlcr", "last"),))),
)


def rule_d_step(rule_id: str) -> str:
    """The step name ("2a", "2b", "2c", "post-2d") of one of the four rule D ids of RULE_D_STEPS, matched exactly;
    ValueError for any other id (a sensitivity id, an unknown rule D id). Scorer versions are kept per step (step 2b,
    17 Oct 2026: a line's version is the one its read rule's step writes)."""
    steps = {r.rule_id: s for s, r in RULE_D_STEPS}
    _need(rule_id in steps, f"not one of the four rule D ids of RULE_D_STEPS: {rule_id!r}")
    return steps[rule_id]


def rule_label(rule_id: str) -> str:
    """A short printable label: the step name of a known rule D id ("2a", "post-2d"), ``<name>@<step>`` for a
    sensitivity id over one, the full id otherwise (design 2.7: "(S_whole_turn@post-2d; D1)")."""
    steps = {r.rule_id: s for s, r in RULE_D_STEPS}
    if rule_kind(rule_id) == "rule_d":
        return steps.get(rule_id, rule_id)
    name, _ = parse_sensitivity_id(rule_id)
    base = rule_id.partition("@")[2]
    return f"{name}@{steps.get(base, base)}"


def canonical_coordinates(coords: Mapping[str, str]) -> str:
    """``key=value`` pairs sorted by key, joined by commas (design 2.8). Keys and values may not hold ``,``, ``=``
    or ``@``; the empty mapping is refused (``any`` is a grant word, not a coordinate)."""
    _need(bool(coords), "coordinates may not be empty")
    for k, v in coords.items():
        for x in (k, v):
            _need(isinstance(x, str) and bool(x) and not any(c in x for c in ",=@"),
                  f"coordinate part {x!r} is empty or holds , = or @")
    return ",".join(f"{k}={coords[k]}" for k in sorted(coords))


def parse_coordinates(text: str) -> dict[str, str] | Literal["any"]:
    """Inverse of canonical_coordinates, or ``"any"``; ValueError when ``text`` is not canonical."""
    if text == "any":
        return "any"
    pairs = [p.partition("=") for p in text.split(",")]
    _need(all(sep == "=" for _, sep, _ in pairs), f"coordinates not key=value: {text!r}")
    d = {k: v for k, _, v in pairs}
    _need(len(d) == len(pairs) and canonical_coordinates(d) == text, f"coordinates not canonical: {text!r}")
    return d


