class CellRow(_Sealed):
    """One score record joined to the sealed text it was scored on (design 2.7), issued only by report.py. The read
    rule, the mode and includes_reasoning are computed from the text (or ``undelivered_under``); ``prompt_id`` and
    ``sample`` are computed from the key. ``same_completion_id`` is the Completion's (design 2.3, Revision 4), so a
    DeltaCell recognises a pair whose two rows hold one completion."""

    ISSUER_NAME: ClassVar[str] = "report"
    completion_key: str
    same_completion_id: str
    spec_id: str
    family: Family
    text: DeliveredText | SensitivityText | None
    undelivered_under: str | None
    undelivered_reason: UndeliveredReason | None
    scorer: ScorerId
    label: str
    score: float | None
    unparsed_reason: UnparsedReason | None
    verdict_view: str | None
    provenance: Provenance
    generation: RowGeneration
    generation_config_id: str
    prompt_token_hash: str
    dataset: str | None
    tool_render: Literal["slot", "system_text_legacy"]
    tokenizer_revision_recorded: bool
    prefix_token_parity: bool | None
    mac: str

    def _check_shape(self) -> None:
        prompt_id = _check_key(self.completion_key).prompt_id
        _hex(self.same_completion_id, HEX64, "same_completion_id")
        _hex(self.spec_id, HEX16, "spec_id")
        _hex(self.generation_config_id, HEX16, "generation_config_id")
        _hex(self.prompt_token_hash, HEX16, "prompt_token_hash")
        _need(family_of(prompt_id) == self.family and self.family in FAMILY_LABELS, "family is the scored prompt's")
        _need(self.label in FAMILY_LABELS[self.family], f"label {self.label!r} is not a {self.family} label")
        _need((self.text is None) != (self.undelivered_under is None), "exactly one of text and undelivered_under")
        _need((self.text is None) == (self.undelivered_reason is not None), "an undelivered row names its reason")
        _need((self.text is None) == (self.label == "no_answer"), "no_answer exactly when nothing was delivered")
        if self.label in _NA_UP:
            _need(self.score is None, f"a {self.label} row scores None")
        if self.score is not None:
            _need(0.0 <= self.score <= 1.0, "score lies in [0, 1]")
        _need(self.unparsed_reason is None or self.label == "unparsed", "only an unparsed row has an unparsed reason")
        t = self.text
        if t is not None:
            _need(t.completion_key == self.completion_key and t.spec_id == self.spec_id, "the text is this row's")
            _need(t.family == self.family, "the sealed text's family differs from the score record's (re-review 2 "
                                           "item 4)")
            _need(t.provenance == self.provenance, "provenance differs from the sealed text's")
        else:
            registered_rule(self.undelivered_under)
        _need(self.scorer.read_rule == self.read_rule, "the scorer's read rule is the row's read rule")
        if self.verdict_view is not None:
            _need(bool(_VERDICT_VIEW.fullmatch(self.verdict_view)), f"unknown verdict view {self.verdict_view!r}")
        _need((self.verdict_view is not None) == (self.family in JUDGED_FAMILIES and t is not None),
              "a delivered judged row names its verdict view; no other row has one")
        _need(self.generation.provenance == self.provenance, "generation provenance is the row's")
        _need((self.prefix_token_parity is not None) == (self.provenance == "continuation"),
              "prefix_token_parity is a continuation's fact")

    @computed_field
    @property
    def prompt_id(self) -> str:
        return split_completion_key(self.completion_key).prompt_id

    @computed_field
    @property
    def sample(self) -> int:
        return split_completion_key(self.completion_key).sample

    @computed_field
    @property
    def read_rule(self) -> str:
        return self.text.rule_id if self.text is not None else self.undelivered_under  # type: ignore[return-value]

    @computed_field
    @property
    def mode(self) -> str:
        return self.text.mode if self.text is not None else "undelivered"

    @computed_field
    @property
    def includes_reasoning(self) -> bool:
        return self.text.includes_reasoning if self.text is not None else False

    @property
    def cut_at_cap(self) -> bool:
        return isinstance(self.text, DeliveredText) and self.text.cut_at_cap


def _agg(values: list[tuple[float, str | None]], how: str) -> float | None:
    """item_pooled: the mean over rows; dataset_mean: the unweighted mean of the per-dataset means (audit 19)."""
    if not values:
        return None
    if how == "item_pooled":
        return sum(v for v, _ in values) / len(values)
    groups: dict[str | None, list[float]] = defaultdict(list)
    for v, d in values:
        _need(d is not None, "a dataset_mean metric needs each row's dataset")
        groups[d].append(v)
    return sum(sum(g) / len(g) for g in groups.values()) / len(groups)


def _row_class(row: CellRow, metric: MetricSpec) -> tuple[str, float | None]:
    """('value', v) for a row the projection values; ('undelivered', None) for a row that delivered nothing or, under
    ``cut_at_cap = censored``, ran into the cap; ('unparsed', None) for an unparsed row."""
    if row.text is None or (metric.cut_at_cap == "censored" and row.cut_at_cap):
        return "undelivered", None
    if row.label == "unparsed":
        return "unparsed", None
    if metric.value_from == "score":
        _need(row.score is not None, f"a delivered {row.label!r} row of a score-valued metric carries a score")
        return "value", float(row.score)  # type: ignore[arg-type]
    _need(row.label in metric.projection, f"label {row.label!r} is not in {metric.metric_id}'s projection")
    return "value", metric.projection[row.label]


def _valued(classes: list[tuple[str, float | None, str | None]], metric: MetricSpec,
            censored: float | None) -> list[tuple[float, str | None]]:
    """Row values with every censored row at ``censored``, or at its cited all_rows value when ``censored`` is None;
    a row whose cited value is ``excluded`` is left out then (step 4; CensoredValue)."""
    out = []
    for c, v, d in classes:
        if c == "value":
            out.append((v, d))
        elif censored is None:
            cv = metric.censored_as[c].value  # type: ignore[index]
            if cv != "excluded":
                out.append((cv, d))
        else:
            out.append((censored, d))
    return out


def _generation_basis(rows: tuple[CellRow, ...]) -> GenerationBasis:
    gens = [r.generation for r in rows]
    ropes, mmls = {g.rope_scaling for g in gens}, {g.max_model_len for g in gens}
    _need(len(ropes) == 1 and len(mmls) == 1, "rows of two generation bases in one cell (rope scaling or model "
                                              "length differ; design 9 (c))")
    rope, mml = ropes.pop(), mmls.pop()
    provs = {g.provenance for g in gens}
    if len(provs) == 1 and len({g.max_tokens for g in gens}) == 1:
        return GenerationBasis(kind="single", rope_scaling=rope, max_model_len=mml, max_tokens=gens[0].max_tokens,
                               provenance=gens[0].provenance)
    ext = provs - {"first_pass"}
    _need("first_pass" in provs and len(ext) == 1 and ext <= {"redraw", "continuation"},
          f"rows of two generation bases in one cell ({sorted(provs)})")
    fp = [g for g in gens if g.provenance == "first_pass"]
    ex = [g for g in gens if g.provenance != "first_pass"]
    first, extended = {g.max_tokens for g in fp}, {g.max_tokens for g in ex}
    _need(len(first) == 1 and len(extended) == 1 and {g.first_pass_max_tokens for g in ex} == first,
          "rows of two generation bases in one cell (token budgets differ)")
    _need(all(g.finish_reason != "length" for g in fp), "an extended basis holds first-pass rows that stopped below "
                                                       "the first cap; a cut one is replaced by its extension")
    return GenerationBasis(kind="extended", rope_scaling=rope, max_model_len=mml, max_tokens=first.pop(),
                           provenance="first_pass", extension_max_tokens=extended.pop(),
                           extension_provenance=ext.pop())  # type: ignore[arg-type]


class ReportCell(_Sealed):
    """One cell (design 2.7), issued only by ``report.cell`` from CellRows. Everything but the metric, coordinates,
    view, stratum and rows is a computed field: passing one is an extra field and fails. Refused: rows of two read
    rules, an unregistered read rule, a sensitivity cell outside its grant's ``cell:`` lines, a two-way reading
    without ``mixed_modes``, rows of two generation bases, forced rows outside budget_forced (and free-run rows inside
    it), an extension beside its own first pass, two scorer ids, a row of another family."""

    ISSUER_NAME: ClassVar[str] = "report"
    metric: MetricSpec
    coordinates: dict[str, str]
    view: CensoringView
    item_stratum: Literal["all", "clean"]
    basis: tuple[CellRow, ...]
    mac: str

    def _check_shape(self) -> None:
        self._analysis()

    def _analysis(self) -> dict[str, Any]:
        rows, m = self.basis, self.metric
        _need(bool(rows), "a cell aggregates at least one row")
        reg = active_registry()
        reg.coordinates.check(self.coordinates)
        rules = {r.read_rule for r in rows}
        _need(len(rules) == 1, f"one read rule per cell, got {sorted(rules)}")
        rule = rules.pop()
        column = "primary" if registered_rule(rule) == "rule_d" else "sensitivity"
        owners: tuple[str, ...] = ()
        grant = None
        if column == "sensitivity":
            grant = reg.decisions.cell_grant(rule, m.metric_id, self.coordinates)
            _need(grant is not None, f"cell {m.metric_id}@{canonical_coordinates(self.coordinates)} is outside every "
                                     f"grant of {rule}")
            owners = (grant.record,)
        if m.sensitivity_rule is not None:
            _need(column == "sensitivity" and parse_sensitivity_id(rule)[0] == m.sensitivity_rule,
                  f"metric {m.metric_id} reads under {m.sensitivity_rule}")
        _need(all(r.family == m.family for r in rows), "a row of another family")
        reasoning = {r.includes_reasoning for r in rows if r.text is not None}
        if len(reasoning) > 1:
            _need(grant is not None and rule in grant.mixed_modes, f"two-way reading in one cell: no grant holds "
                                                                   f"mixed_modes:{rule}")
        scorers = {(r.scorer.name, r.scorer.version) for r in rows}
        classes_ = {scorer_class(r.scorer) for r in rows}
        _need(len(classes_) == 1, f"one scorer version per cell (or the two stamps of one kept/re-asked pair), got "
                                  f"{sorted(scorers)}")
        keys = {r.completion_key for r in rows}
        _need(len(keys) == len(rows), "a completion appears once in a cell")
        _need(not any(r.generation.first_pass_key in keys for r in rows),
              "a continuation or forced row sits beside the first-pass row it extends")
        prov = Counter(r.provenance for r in rows)
        if self.view == "budget_forced":
            _need(set(prov) == {"forced_close"}, "a budget_forced cell holds forced_close rows only (design 9 (a))")
        else:
            _need("forced_close" not in prov, "a forced_close row sits only in a budget_forced cell")
        basis = _generation_basis(rows)
        views = {r.verdict_view for r in rows if r.verdict_view is not None}
        if column == "primary" and m.family in JUDGED_FAMILIES and views - {"delivered"}:
            status = "pending"
        elif self.view == "bracket" and m.statistic == "nonlinear" and m.bound_method == "not_bracketable":
            status = "not_bracketable"
        else:
            status = "ok"
        classes = [(*_row_class(r, m), r.dataset) for r in rows]
        estimate = bracket = worst = None
        n = len(rows)
        if m.statistic == "linear":
            worst = (_agg(_valued(classes, m, 0.0), m.aggregation), _agg(_valued(classes, m, 1.0), m.aggregation))
            if self.view in ("all_rows", "budget_forced"):
                kept_all = _valued(classes, m, None)
                n, estimate = len(kept_all), _agg(kept_all, m.aggregation)
            elif self.view == "delivered_only":
                kept = [(v, d) for c, v, d in classes if c == "value"]
                n, estimate = len(kept), _agg(kept, m.aggregation)
            else:
                bracket = worst
        if status == "pending":
            estimate = bracket = None
        return {
            "read_rule": rule, "column": column, "base": rule_base(rule), "owner_decisions": owners,
            "generation_basis": basis, "provenance": dict(sorted(prov.items())), "status": status,
            "scorer_ids": tuple(sorted({r.scorer.stamp for r in rows})),
            "spec_ids": tuple(sorted({r.spec_id for r in rows})), "verdict_views": tuple(sorted(views)),
            "generation_config_ids": tuple(sorted({r.generation_config_id for r in rows})),
            "datasets": tuple(sorted({r.dataset for r in rows if r.dataset is not None})),
            "estimate": estimate, "bracket": bracket, "worst_case": worst, "n": n, "n_rows": len(rows),
            "undelivered": dict(sorted(Counter(r.undelivered_reason for r in rows if r.text is None).items())),
            "unparsed": dict(sorted(Counter(r.unparsed_reason or "unrecorded" for r in rows
                                            if r.label == "unparsed").items())),
            "excluded_unparsed_n": (sum(c == "unparsed" for c, _, _ in classes)
                                    if m.censored_as["unparsed"].value == "excluded" else 0),
            "scorer_classes": tuple(sorted(classes_)),
            "kept_n": sum(1 for r in rows if r.text is not None and kept_reasked_role(r.scorer) == "kept"),
            "cut_at_cap_n": sum(r.cut_at_cap for r in rows),
            "cut_at_inner_open_n": sum(isinstance(r.text, DeliveredText) and r.text.cut_at_inner_open for r in rows),
            "blocks_removed_n": sum(isinstance(r.text, DeliveredText) and r.text.blocks_removed > 0 for r in rows),
            "tool_render_legacy_n": sum(r.tool_render == "system_text_legacy" for r in rows),
            "tokenizer_revision_not_recorded_n": sum(not r.tokenizer_revision_recorded for r in rows),
            "prefix_parity_failed_n": sum(r.prefix_token_parity is False for r in rows),
            "max_model_len_not_recorded_n": sum(r.generation.max_model_len == "not_recorded" for r in rows),
            "modes": dict(sorted(Counter(f"{r.mode}{'+reasoning' if r.includes_reasoning else ''}"
                                         for r in rows).items())),
        }

    def item_lists(self, end: Literal["all_rows", "low", "high", "delivered_only"]) -> tuple[list[str],
                                                                                         dict[str, list[float]]]:
        """(item order, {item: row values}) under the valuation ``end`` (step 4): ``all_rows`` values a censored row at
        its cited all_rows value and leaves an ``excluded`` one out, ``low`` and ``high`` value every censored row at 0
        and at 1 (the bracket's ends), ``delivered_only`` keeps the valued rows only. A composite over several cells
        of one item set pools these lists per item (report.composite_level)."""
        m = self.metric
        _need(m.statistic == "linear", "item lists are defined for a linear statistic")
        order: dict[str, None] = {}
        out: dict[str, list[float]] = defaultdict(list)
        cen = {"all_rows": None, "low": 0.0, "high": 1.0}
        for r in self.basis:
            order.setdefault(r.prompt_id, None)
            c, v = _row_class(r, m)
            if end == "delivered_only":
                if c == "value":
                    out[r.prompt_id].append(v)  # type: ignore[arg-type]
                continue
            got = _valued([(c, v, None)], m, cen[end])
            if got:
                out[r.prompt_id].append(got[0][0])
        return list(order), dict(out)

