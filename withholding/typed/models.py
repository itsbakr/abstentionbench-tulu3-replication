class PromptRecord(_Frozen):
    """One prompt with its typed gold (design 2.2). Dispatch never parses raw JSON text: the family is a field that
    the id's prefix and the gold type must agree with. ``tool_render = system_text_legacy`` (the stored When2Call rows,
    which carry the tools as system text) is admitted only when validated with the context ``{"backfill": True}``."""

    id: str
    family: Family
    behavior: Literal["abstain", "ask", "admit_impossible", "confidence", "control", "refuse_control"]
    messages: tuple[Message, ...]
    system_source: Literal["benchmark", "none"]
    tools: ToolSet
    tool_render: Literal["slot", "system_text_legacy"]
    answer_format: Literal["boxed", "tac_tags", "code_block", "free_text", "tool_call_or_text"]
    gold: Gold
    item_status: Literal["clean", "not_clean", "unscreened"]
    prompt_sha: str
    edit: Edit | None = None

    @model_validator(mode="after")
    def _invariants(self, info: ValidationInfo) -> PromptRecord:
        _need(family_of(self.id) == self.family, f"id {self.id!r} does not start with family {self.family}")
        _need(self.gold.kind == GOLD_KIND[self.family], f"gold {self.gold.kind} does not fit family {self.family}")
        _need(bool(self.messages), "a prompt has at least one message")
        _need((self.system_source == "benchmark") == (self.messages[0].role == "system"),
              "system_source is 'benchmark' exactly when the prompt starts with a system message (R4)")
        if self.family == "reliablemath":  # solvability is stored twice; the two must agree (2.2)
            seg = self.id.split("/")[1]
            if seg in ("unsol", "solve"):
                _need(self.gold.solvable == (seg == "solve"), f"id {self.id!r} says {seg} but gold.solvable is "
                                                              f"{self.gold.solvable}")
        if self.family == "when2call":  # tools come from the parsed meta.tools, never from a message (2.2)
            _need(self.tools.state != "absent", "a When2Call prompt declares its tools (declared or declared_empty)")
        if self.tool_render == "system_text_legacy":
            _need(bool(info.context) and info.context.get("backfill") is True,
                  "tool_render system_text_legacy is admitted only by the backfill adapter (review item 6)")
        else:  # no message may carry a tool's serialized text (2.2, review item 6)
            for t in self.tools.tools:
                for m in self.messages:
                    _need(t.legacy_json() not in m.content, f"tool {t.name} is serialized in a {m.role} message")
                    _need(not (t.name in m.content and t.description and t.description in m.content),
                          f"tool {t.name} appears with its description in a {m.role} message")
        _need(self.prompt_sha == prompt_sha_of(self.messages, self.tools),
              "prompt_sha is not the sha of the messages and tools")
        return self

    @property
    def question(self) -> str:
        """The text a judge prompt quotes: the last message's content."""
        return self.messages[-1].content


def check_tool_render(rendered: str, prompt: PromptRecord, spec: TemplateSpec) -> None:
    """The render check of design 2.2 for declared tools: every tool name occurs in the rendered prompt outside every
    message's own content (so the template, not a message, put it there), and the spec's no-tools marker is absent.
    A spec with no tool slot cannot carry declared tools. ValueError on failure."""
    if prompt.tools.state != "declared":
        return
    _need(spec.tool_slot != "none", "declared tools under a template with no tool slot")
    outside = rendered
    for m in prompt.messages:
        if m.content:
            outside = outside.replace(m.content, "")
    for t in prompt.tools.tools:
        _need(t.name in outside, f"tool {t.name} is not in the template's tool slot")
    if spec.no_tools_marker is not None:
        _need(spec.no_tools_marker not in rendered, "the render carries the template's no-tools marker (audit 4)")


