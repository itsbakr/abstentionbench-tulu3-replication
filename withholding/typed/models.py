def scorer_class(scorer: Any) -> str:
    """The scorer a cell and a delta compare: the stamp itself, or for a stamp of a kept/re-asked pair the pair's name
    (``<name>/<kept>+<re-asked>``), so a cell holding both counts one scorer (KEPT_REASKED_STAMPS)."""
