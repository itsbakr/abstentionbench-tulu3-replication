class DeclaredDifference(_Frozen):
    """A field on which a delta's two cells may differ, with the decision that admits it: a record of the decisions note
    or a cited design contrast, resolved in the registry (design 2.7). The read rule and the view are not DeltaFields,
    and reading pairs are admitted only by a record."""

    field: DeltaField
    decision: str

    @model_validator(mode="after")
    def _resolves(self) -> DeclaredDifference:
        reg = active_registry()
        is_record = any(r.id == self.decision for r in reg.decisions.records)
        _need(is_record or self.decision in reg.design_contrasts,
              f"declaration {self.decision!r} resolves to no record and no cited design contrast")
        _need(is_record or self.field != "reading_pairs", "a design contrast cannot declare reading pairs")
        return self

    @property
    def is_record(self) -> bool:
        return any(r.id == self.decision for r in active_registry().decisions.records)


class DeltaCell(_Sealed):
    """b minus a (design 2.7), issued only by ``report.delta`` from two ReportCell instances. Rows pair on (prompt id,
    sample). Refused: two primary read rules (outright), two read rules without a grant's exact ``delta:`` pair line,
    a view or metric difference (outright), a forced row paired with another provenance (outright), reading pairs in a
    same-rule delta unless declared by a record whose cells' grant holds ``mixed_modes``, and every other difference
    (provenance pairs, generation basis, scorer ids, aggregation, stratum, prompt tokens) unless declared. A
    declaration nothing needs is refused. Censoring and region pairs are counted and printed (D13), and so are, from
    Revision 4, the pairs whose two rows hold one completion (``same_completion``: think_ext's first-pass rows beside
    think's) and the pairs whose prompts differ in content under one id (``prompt_content``: the drift paraphrases)."""

    ISSUER_NAME: ClassVar[str] = "report"
    a: ReportCell
    b: ReportCell
    declared: tuple[DeclaredDifference, ...]
    mac: str

    def _check_shape(self) -> None:
        self._analysis()

    def _analysis(self) -> dict[str, Any]:
        a, b = self.a, self.b
        aa, ba = a._analysis(), b._analysis()
        _need(a.metric.metric_id == b.metric.metric_id, "a delta pairs two cells of one metric")
        _need(a.view == b.view, "a view difference is refused whatever is declared (spot check item 3)")
        decl = {d.field: d for d in self.declared}
        _need(len(decl) == len(self.declared), "a DeltaField is declared once")
        reg = active_registry().decisions
        ra, rb = aa["read_rule"], ba["read_rule"]
        owners: list[str] = []
        cross = ra != rb
        if cross:
            _need(not (aa["column"] == ba["column"] == "primary"),
                  "two primary rule ids: refused outright, whatever is declared")
            g = reg.delta_grant(ra, rb)
            _need(g is not None, f"two read rules ({ra} ~ {rb}) and no grant holds that delta: pair line")
            owners.append(g.record)
        elif aa["column"] == "sensitivity":
            owners.extend(o for o in aa["owner_decisions"] + ba["owner_decisions"] if o not in owners)
        pa = {(r.prompt_id, r.sample): r for r in a.basis}
        pb = {(r.prompt_id, r.sample): r for r in b.basis}
        _need(len(pa) == len(a.basis) and len(pb) == len(b.basis), "rows pair on (prompt id, sample) once per cell")
        common = [k for k in pa if k in pb]
        kinds: Counter[str] = Counter()
        for k in common:
            x, y = pa[k], pb[k]
            if (x.text is None) != (y.text is None):
                kinds["censoring"] += 1
            elif x.text is None:
                kinds["both_undelivered"] += 1
            elif x.includes_reasoning != y.includes_reasoning:
                kinds["reading"] += 1
            elif x.mode != y.mode:
                kinds["region"] += 1
            else:
                kinds["same_mode"] += 1
            if x.provenance != y.provenance:
                _need("forced_close" not in (x.provenance, y.provenance),
                      "a forced_close row pairs only with a forced_close row, whatever is declared (design 9 (a))")
                kinds["provenance"] += 1
            if x.prompt_token_hash != y.prompt_token_hash:
                kinds["prompt_tokens"] += 1
            if x.same_completion_id == y.same_completion_id:
                kinds["same_completion"] += 1
            if split_completion_key(x.completion_key).prompt_sha != split_completion_key(y.completion_key).prompt_sha:
                kinds["prompt_content"] += 1
        needs = set()
        if kinds["reading"] and not cross:
            d = decl.get("reading_pairs")
            grants = [g for g in reg.grants if g.record in aa["owner_decisions"]]
            _need(aa["column"] == "sensitivity" and d is not None and d.is_record
                  and any(ra in g.mixed_modes for g in grants),
                  f"{kinds['reading']} reading pairs: declare reading_pairs with a record whose grant holds "
                  f"mixed_modes:{ra}")
            needs.add("reading_pairs")
        if kinds["provenance"]:
            needs.add("provenance_pairs")
        if aa["generation_basis"] != ba["generation_basis"]:
            needs.add("generation_basis")
        if aa["scorer_classes"] != ba["scorer_classes"]:   # step 4: a kept/re-asked pair is one scorer (scorer_class)
            needs.add("scorer_ids")
        if a.metric.aggregation != b.metric.aggregation:
            needs.add("aggregation")
        if a.item_stratum != b.item_stratum:
            needs.add("item_stratum")
        if kinds["prompt_tokens"]:
            needs.add("prompt_tokens")
        missing = needs - set(decl)
        _need(not missing, f"{sorted(missing)} differ undeclared; declare each with a record or a cited design contrast")
        idle = set(decl) - needs
        _need(not idle, f"{sorted(idle)} declared but nothing differs")
        owners.extend(d.decision for d in self.declared if d.is_record and d.decision not in owners)
        m = a.metric
        estimate = worst = None
        if m.statistic == "linear" and common:
            ca = [(*_row_class(pa[k], m), pa[k].dataset) for k in common]
            cb = [(*_row_class(pb[k], m), pb[k].dataset) for k in common]
            agg = m.aggregation
            lo = _agg(_valued(cb, m, 0.0), agg) - _agg(_valued(ca, m, 1.0), agg)
            hi = _agg(_valued(cb, m, 1.0), agg) - _agg(_valued(ca, m, 0.0), agg)
            worst = (lo, hi)
            if a.view in ("all_rows", "budget_forced"):
                estimate = _agg(_valued(cb, m, None), agg) - _agg(_valued(ca, m, None), agg)
            elif a.view == "delivered_only":
                both = [i for i in range(len(common)) if ca[i][0] == "value" and cb[i][0] == "value"]
                if both:
                    estimate = (_agg([(cb[i][1], cb[i][2]) for i in both], agg)
                                - _agg([(ca[i][1], ca[i][2]) for i in both], agg))
        if "pending" in (aa["status"], ba["status"]):
            estimate = worst = None
        return {"column": "primary" if aa["column"] == ba["column"] == "primary" else "sensitivity",
                "read_rules": (ra, rb), "owner_decisions": tuple(owners), "n_paired": len(common),
                "n_a": aa["n_rows"], "n_b": ba["n_rows"], "pairs": dict(sorted(kinds.items())),
                "differences": tuple(sorted(needs)), "spec_ids_differ": aa["spec_ids"] != ba["spec_ids"],
                "estimate": estimate, "worst_case": worst,
                "status": "pending" if "pending" in (aa["status"], ba["status"]) else aa["status"]}

    @computed_field
    @property
    def column(self) -> Literal["primary", "sensitivity"]:
        return self._analysis()["column"]

    @computed_field
    @property
    def read_rules(self) -> tuple[str, str]:
        return self._analysis()["read_rules"]

    @computed_field
    @property
    def owner_decisions(self) -> tuple[str, ...]:
        return self._analysis()["owner_decisions"]

    @computed_field
    @property
    def n_paired(self) -> int:
        return self._analysis()["n_paired"]

    @computed_field
    @property
    def paired_modes(self) -> dict[str, int]:
        """Pair counts by kind: censoring, both_undelivered, reading, region, same_mode, provenance, prompt_tokens."""
        return self._analysis()["pairs"]

    @computed_field
    @property
    def differences(self) -> tuple[str, ...]:
        return self._analysis()["differences"]

    @computed_field
    @property
    def estimate(self) -> float | None:
        return self._analysis()["estimate"]

    @computed_field
    @property
    def bracket(self) -> tuple[float, float] | None:
        """The worst-case pair (W8.5.2): b's low end minus a's high end, then b's high end minus a's low end."""
        return self._analysis()["worst_case"]

    def _suffix(self) -> str:
        an = self._analysis()
        dagger = "†" if self.declared else ""
        if an["column"] == "primary" and not an["owner_decisions"]:
            return dagger
        ra, rb = an["read_rules"]
        rules = rule_label(ra) if ra == rb else f"{rule_label(ra)} vs {rule_label(rb)}"
        return f"{dagger} ({rules}; {', '.join(an['owner_decisions'])})"

    def item_values(self, end: Literal["all_rows", "low", "high", "delivered_both"]) -> tuple[list[float],
                                                                                         list[float]]:
        """(a's, b's) per-item values over the pairs this delta holds, items in the order a's basis first names them
        (the reports' order: their paired bootstrap walks the first stage's items). An item's value on a side is the mean
        of its paired rows there under the valuation ``end``: ``all_rows`` values a censored row at its cited all_rows
        value (an ``excluded`` one is left out), ``low`` values every censored row of a at 1 and of b at 0, ``high`` the
        reverse (the worst-case pair, W8.5.2), ``delivered_both`` keeps only the pairs valued on both sides (delivered
        and parsed at both: the finished-at-both delta under D18). An item enters when both sides keep a value."""
        order, va, vb = self.item_lists(end)
        items = [i for i in order if va.get(i) and vb.get(i)]
        return ([sum(va[i]) / len(va[i]) for i in items], [sum(vb[i]) / len(vb[i]) for i in items])

    def item_lists(self, end: Literal["all_rows", "low", "high", "delivered_both"]) -> tuple[
            list[str], dict[str, list[float]], dict[str, list[float]]]:
        """(item order, {item: a's row values}, {item: b's row values}) under the valuation ``end`` (``item_values``
        averages them); a composite of several deltas over one item set pools these lists (report.composite)."""
        m = self.a.metric
        _need(m.statistic == "linear", "item values are defined for a linear statistic")
        pa = {(r.prompt_id, r.sample): r for r in self.a.basis}
        pb = {(r.prompt_id, r.sample): r for r in self.b.basis}
        order: dict[str, None] = {}
        for r in self.a.basis:
            if (r.prompt_id, r.sample) in pb:
                order.setdefault(r.prompt_id, None)
        va: dict[str, list[float]] = defaultdict(list)
        vb: dict[str, list[float]] = defaultdict(list)
        cens = {"low": (1.0, 0.0), "high": (0.0, 1.0)}
        for k, x in pa.items():
            y = pb.get(k)
            if y is None:
                continue
            (cx, vx), (cy, vy) = _row_class(x, m), _row_class(y, m)
            if end == "delivered_both":
                if cx == "value" and cy == "value":
                    va[k[0]].append(vx)  # type: ignore[arg-type]
                    vb[k[0]].append(vy)  # type: ignore[arg-type]
                continue
            for c, v, side, cen in ((cx, vx, va, None if end == "all_rows" else cens[end][0]),
                                    (cy, vy, vb, None if end == "all_rows" else cens[end][1])):
                got = _valued([(c, v, None)], m, cen)
                if got:
                    side[k[0]].append(got[0][0])
        return list(order), dict(va), dict(vb)

    def interval(self, end: Literal["all_rows", "low", "high", "delivered_both"]) -> dict[str, float] | None:
        """The paired item bootstrap of ``end``'s item values (INTERVAL_SPEC: the reports' statistic,
        withholding.analysis.bootstrap.paired_bootstrap_delta); None below INTERVAL_SPEC's minimum item count."""
        a, b = self.item_values(end)
        if len(a) < INTERVAL_SPEC["min_items"]:
            return None
        # one implementation of the statistic: the reports' own
        from withholding.analysis.bootstrap import paired_bootstrap_delta

        d = paired_bootstrap_delta(a, b, n_boot=INTERVAL_SPEC["n_boot"], seed=INTERVAL_SPEC["seed"],
                                   alpha=INTERVAL_SPEC["alpha"])
        return {"delta": d["delta"], "lo": d["lo"], "hi": d["hi"], "n_items": d["n_items"]}

    def verdict(self, prereg: PreregRule | None = None) -> dict[str, Any]:
        """The delta as RESULTS quotes it (D7 with D18). The verdict is the preregistered label of the all-rows delta
        with its interval. Each end of the worst-case bracket is read as a point and with its own interval (the ends'
        valuations, ``item_values``), and the cell prints as a point only when both ends, read both ways, give the
        verdict's label, with its direction where the rule's test is directional (``d7_reading``); otherwise as its
        bracket (D7: "at the +0.013 end the label cannot be MOVEMENT, so the cell prints its bracket"; D18: "a point
        only when both ends and each end's interval give the label"; its example, an end that reads as equivalence as
        a point but excludes 0 below the SESOI with its interval, prints as a bracket). Beside it: the
        delivered-at-both delta (W8.5.2's finished-at-both under D18) with its interval. ``pending`` prints no number;
        a delta of fewer items than the interval needs is ``not_computed``."""
        an = self._analysis()
        out: dict[str, Any] = {"status": an["status"], "rule": None if prereg is None else prereg.rule_id}
        if an["status"] != "ok" or an["worst_case"] is None:
            out["quote"] = an["status"] if an["status"] != "ok" else "not_computed"
            return out
        ivs = {e: self.interval(e) for e in ("all_rows", "low", "high", "delivered_both")}
        out.update(ivs)
        allr = ivs["all_rows"]
        if allr is None or ivs["low"] is None or ivs["high"] is None:
            out["status"] = "not_computed"
            out["quote"] = "not_computed"
            return out
        lo_end, hi_end = ivs["low"], ivs["high"]
        out.update(d7_reading(prereg, allr, lo_end, hi_end))
        point = out["point"]
        suffix = self._suffix()
        out["quote"] = (f"{allr['delta']:+.3f}{suffix}" if point
                        else f"[{lo_end['delta']:+.3f}, {hi_end['delta']:+.3f}]{suffix}")
        return out

    def quote(self, prereg: PreregRule | None = None) -> str:
        """D7 with D18 on a delta (``verdict``): the point only when both ends of the worst-case bracket, read as points
        and with their own intervals, give the preregistered label (with its direction under a directional test);
        otherwise the bracket with no point."""
        return self.verdict(prereg)["quote"]

    def render(self) -> str:
        an = self._analysis()
        if an["status"] != "ok":
            return an["status"]
        if self.a.view == "bracket":
            lo, hi = an["worst_case"]
            return f"[{lo:+.3f}, {hi:+.3f}]{self._suffix()}"
        return ("n/a" if an["estimate"] is None else f"{an['estimate']:+.3f}") + self._suffix()


