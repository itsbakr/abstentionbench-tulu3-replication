class ActiveRegistry(_Frozen):
    """What the validators consult (design 2.3, 2.5, 2.7, 2.8): the decisions note with its grants, the taken scorer
    stamps, the cited design contrasts, the metric ids and coordinate scheme, the families with item_status data (whose
    tables need the clean stratum, N5), and the current primary rule once a step has run (None in step 0)."""

    decisions: DecisionsNote
    taken_stamps: tuple[TakenStamp, ...]
    design_contrasts: dict[str, Citation]
    metric_ids: dict[str, str]
    coordinates: CoordinateScheme
    families_with_item_status: frozenset[str]
    current_primary_rule: str | None = None

    @model_validator(mode="after")
    def _current(self) -> ActiveRegistry:
        if self.current_primary_rule is not None:
            _need(self.current_primary_rule in self.decisions.rule_d_ids, "the current primary rule is a registered "
                                                                         "rule D id")
        return self

    @classmethod
    def default(cls, path: Path | str = DECISIONS_NOTE) -> ActiveRegistry:
        """The step 0 registry: the decisions note as written (unsigned is fine), the code's taken stamps, and the
        families of results/c_data/item_status.json (reliablemath on 15 Oct)."""
        fams: frozenset[str] = frozenset()
        if ITEM_STATUS.exists():
            fams = frozenset(k.split("/", 1)[0] for k in json.loads(ITEM_STATUS.read_text(encoding="utf-8")))
        return cls(decisions=load_decisions(path), taken_stamps=CODE_TAKEN_STAMPS,
                   design_contrasts=dict(STEP0_DESIGN_CONTRASTS), metric_ids=dict(STEP0_METRIC_IDS),
                   coordinates=STEP0_COORDINATES, families_with_item_status=fams)

    def with_taken_stamps(self, stamps: tuple[TakenStamp, ...]) -> ActiveRegistry:
        """A copy with more taken stamps. Nothing in step 0 calls it: CODE_TAKEN_STAMPS is written by hand, and the
        step 0 verifier found every non-recognition stamp on disk in it; a later step that scans stamps adds here."""
        return ActiveRegistry(**{**{k: getattr(self, k) for k in type(self).model_fields},
                                 "taken_stamps": self.taken_stamps + tuple(stamps)})

    def taken_under(self, name: str, version: str) -> frozenset[str]:
        """The read rules a (name, version) is already taken under."""
        return frozenset(t.read_rule for t in self.taken_stamps if (t.name, t.version) == (name, version))


_ACTIVE: list[ActiveRegistry] = []


def active_registry() -> ActiveRegistry:
    """The registry the validators read; loaded from the decisions note on first use (RegistryError if it does not
    load)."""
    if not _ACTIVE:
        _ACTIVE.append(ActiveRegistry.default())
    return _ACTIVE[-1]


def install_registry(reg: ActiveRegistry) -> None:
    """Make ``reg`` the active registry (registry.py at load; a test on a scratch note)."""
    _ACTIVE.clear()
    _ACTIVE.append(reg)


@contextlib.contextmanager
def using_registry(reg: ActiveRegistry) -> Iterator[ActiveRegistry]:
    """Run a block under ``reg``, then restore the previous registry (scratch copies of the note in tests)."""
    prev = list(_ACTIVE)
    install_registry(reg)
    try:
        yield reg
    finally:
        _ACTIVE.clear()
        _ACTIVE.extend(prev)


