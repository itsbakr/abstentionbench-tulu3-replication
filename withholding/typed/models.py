def canonical_json(obj: Any) -> str:
    """Canonical JSON: sorted keys, no whitespace, UTF-8 kept. Every computed id and sha here hashes this form."""
    return json.dumps(obj, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def sha256_hex(text: str) -> str:
    """sha256 of the UTF-8 encoding of ``text``, 64 hex."""
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def section_sha(body: str) -> str:
    """The content sha of a section body (design 2.8; Revision 6, 17 Oct): sha256 of its lines from the first to the
    last non-blank one, line endings dropped, joined by a newline. The blank lines between a section and the next
    heading are not its content: a section appended after the last record, or a separator line added or removed,
    moves no sha, and any edit of a content line does."""
    lines = body.splitlines()
    while lines and not lines[0].strip():
        lines.pop(0)
    while lines and not lines[-1].strip():
        lines.pop()
    return sha256_hex("\n".join(lines))


def _need(cond: bool, msg: str) -> None:
    """Raise ValueError(msg) unless cond; inside a validator pydantic reports it as a ValidationError."""
    if not cond:
        raise ValueError(msg)


def _hex(value: str, pattern: re.Pattern[str], what: str) -> None:
    _need(bool(pattern.fullmatch(value)), f"{what} must match {pattern.pattern}, got {value!r}")


class _Frozen(BaseModel):
    """Base of every model: frozen, extra fields forbidden, strict (design 2.0)."""

    model_config = MODEL_CONFIG


Span = tuple[int, int]


def _spans_ok(spans: tuple[Span, ...], what: str, *, adjacent_ok: bool) -> None:
    """Spans are (start, end) with 0 <= start < end, in text order and disjoint; ``adjacent_ok=False`` also refuses two
    spans that touch (between two delivered spans lies at least one removed block, design 2.3)."""
    prev_end = -1
    for s, e in spans:
        _need(0 <= s < e, f"{what}: span ({s}, {e}) is not 0 <= start < end")
        _need(s >= prev_end if adjacent_ok else s > prev_end, f"{what}: spans overlap, touch or are out of order "
                                                              f"at ({s}, {e})")
        prev_end = e


def _overlaps(a: Span, b: Span) -> bool:
    return a[0] < b[1] and b[0] < a[1]


