def _canon(v: Any) -> Any:
    """The canonical JSON-able form a MAC hashes: a model by its declared fields (computed fields derive from them), a
    set sorted by its canonical JSON, a date as ISO text. The same value gives the same form before and after
    validation (strict mode keeps input values). Step 4 (23 Oct 2026): a nested sealed instance is canonical as its
    class and its own MAC, which already binds every field of it (its text through text_sha): a cell's MAC then covers
    its rows without re-encoding their texts, and a table's its cells (the profile spent half a report's time encoding
    nested texts). The nested instance was verified when it was issued; a frozen model cannot change after."""
    if isinstance(v, _Sealed):
        return {"sealed": type(v).__qualname__, "mac": v.mac}
    if isinstance(v, BaseModel):
        return {k: _canon(getattr(v, k)) for k in type(v).model_fields}
    if isinstance(v, Mapping):
        return {str(k): _canon(x) for k, x in v.items()}
    if isinstance(v, (frozenset, set)):
        return sorted((_canon(x) for x in v), key=canonical_json)
    if isinstance(v, (tuple, list)):
        return [_canon(x) for x in v]
    if isinstance(v, date):
        return v.isoformat()
    if v is None or isinstance(v, (bool, int, float, str)):
        return v
    raise TypeError(f"cannot seal a {type(v).__name__}")


class Issuer:
    """The capability to build one module's sealed types (design 2.0): the per-process HMAC key, generated when the
    issuer is minted and never stored or printed, and the validation-context token. ``claim_issuer`` hands one to
    ``withholding.typed.ingest`` and one to ``withholding.typed.report``, once each per process."""

    __slots__ = ("_check", "_classes", "_key", "_live", "_token", "name")

    def __init__(self, name: str, classes: tuple[type, ...], instance_check: Callable[[Any], None] | None):
        self.name = name
        self._key = secrets.token_bytes(32)
        self._token = object()
        self._classes = frozenset(classes)
        self._check = instance_check
        self._live = True

    def __repr__(self) -> str:
        return f"<Issuer {self.name} {'live' if self._live else 'revoked'}>"

    def authorises(self, cls: type) -> bool:
        """True while live, for the sealed classes this issuer was minted for."""
        return self._live and cls in self._classes

    def context(self) -> dict[str, object]:
        """The validation context under which a sealed class of this issuer accepts construction."""
        return {_TOKEN_KEY: self._token}

    def _mac(self, cls: type, fields: Mapping[str, Any]) -> str:
        payload = canonical_json({"type": cls.__qualname__, "fields": {k: _canon(v) for k, v in fields.items()}})
        return hmac.new(self._key, payload.encode("utf-8"), hashlib.sha256).hexdigest()

    def issue(self, cls: type[_SealedT], /, **fields: Any) -> _SealedT:
        """Build a sealed instance: the MAC covers every declared field except ``text`` and ``mac`` (missing fields at
        their defaults), then the class validates under this issuer's token and verifies it."""
        if not self.authorises(cls):
            raise SealError(f"issuer {self.name!r} cannot issue {cls.__name__}")
        if "mac" in fields:
            raise SealError("the issuer computes the mac; it is never passed")
        sealed = {}
        for k, f in cls.model_fields.items():
            if k in ("text", "mac"):
                continue
            if k in fields:
                sealed[k] = fields[k]
            elif not f.is_required():
                sealed[k] = f.get_default(call_default_factory=True)
        return cls.model_validate({**fields, "mac": self._mac(cls, sealed)}, context=self.context())

    def revoke(self) -> None:
        """No instance issued by a revoked issuer verifies again, and it issues nothing (the self-check's issuer)."""
        self._live = False
        if self in _LIVE_ISSUERS:
            _LIVE_ISSUERS.remove(self)


def _mint_issuer(name: str, classes: tuple[type, ...], instance_check: Callable[[Any], None] | None = None) -> Issuer:
    """Private: a new live issuer. Used by claim_issuer, the import-time self-check and the white-box tests of this
    module; the AST convention forbids importing it anywhere else."""
    issuer = Issuer(name, classes, instance_check)
    _LIVE_ISSUERS.append(issuer)
    return issuer


def claim_issuer(name: Literal["ingest", "report"], *,
                 instance_check: Callable[[Any], None] | None = None) -> Issuer:
    """The issuer of ``withholding.typed.<name>``'s sealed types, handed to that module once per process (call it at
    import). ``instance_check(instance)`` runs on every verification of an instance this issuer built (ingest: the text
    is its completion's raw text over its offsets, and re-running delivery gives the same spans and mode)."""
    caller = sys._getframe(1).f_globals.get("__name__")
    if name not in _ISSUING:
        raise SealError(f"no sealed types are issued by {name!r}")
    module, classes = _ISSUING[name]
    if caller != module:
        raise SealError(f"the {name} issuer is claimed only by {module}, not {caller}")
    if name in _CLAIMED:
        raise SealError(f"the {name} issuer was already claimed in this process")
    _CLAIMED.add(name)
    return _mint_issuer(name, classes, instance_check)


def _issuer_for_token(token: object) -> Issuer | None:
    return next((i for i in _LIVE_ISSUERS if i._token is token and i._live), None)


def verify_seal(inst: Any) -> Any:
    """Re-verify a sealed instance: its MAC under a live issuer of its class, its own shape checks, and that issuer's
    instance check. SealError (a ValueError) on any failure; returns the instance. Pydantic calls this through the
    after-validator whenever a sealed instance is passed as a field value."""
    if not isinstance(inst, _Sealed):
        raise SealError(f"expected a sealed instance, got {type(inst).__name__}")
    cls = type(inst)
    fields = {k: getattr(inst, k, None) for k in cls.model_fields if k not in ("text", "mac")}
    mac = getattr(inst, "mac", "")
    issuer = next((i for i in _LIVE_ISSUERS if i.authorises(cls) and isinstance(mac, str)
                   and hmac.compare_digest(i._mac(cls, fields), mac)), None)
    if issuer is None:
        raise SealError(f"{cls.__name__} seal broken: its fields are not the ones a live issuer issued")
    inst._check_shape()
    if issuer._check is not None:
        issuer._check(inst)
    return inst


class _Sealed(_Frozen):
    """Base of the sealed types: built only under an authorised issuer's token, never copied or constructed without
    validation, re-verified whenever used (module docstring, "The seal")."""

    ISSUER_NAME: ClassVar[str] = "ingest"

    @model_validator(mode="before")
    @classmethod
    def _issued(cls, data: Any, info: ValidationInfo) -> Any:
        ctx = info.context if isinstance(info.context, dict) else {}
        issuer = _issuer_for_token(ctx.get(_TOKEN_KEY))
        if issuer is None or not issuer.authorises(cls):
            raise SealError(f"{cls.__name__} is issued only by withholding.typed.{cls.ISSUER_NAME}")
        return data

    @model_validator(mode="after")
    def _verified(self) -> _Sealed:
        verify_seal(self)
        return self

    def _check_shape(self) -> None:
        """The class's own invariants, re-run on every verification (overridden)."""

    def model_copy(self, *, update: Mapping[str, Any] | None = None, deep: bool = False) -> Any:
        raise SealError(f"{type(self).__name__} is never copied; its issuer re-issues it")

    @classmethod
    def model_construct(cls, _fields_set: set[str] | None = None, **values: Any) -> Any:
        raise SealError(f"{cls.__name__} is never constructed without validation")


_SealedT = Any  # the issue() return type; a TypeVar bound to _Sealed would need runtime generics for no gain


def bound_check(value: Any) -> Any:
    """The ``Delivered`` argument check (design 2.0): only a sealed DeliveredText instance, re-verified; a str, a
    dict or a forged instance is refused."""
    if not isinstance(value, DeliveredText):
        raise SealError(f"a scorer takes a sealed DeliveredText, not {type(value).__name__}")
    return verify_seal(value)


def _check_key(key: str) -> CompletionKeyParts:
    parts = split_completion_key(key)
    family_of(parts.prompt_id)
    return parts


def _check_text(text: str, text_sha: str, spans: tuple[Span, ...] | None, *, nonblank: bool, what: str) -> None:
    _hex(text_sha, HEX64, f"{what}.text_sha")
    _need(sha256_hex(text) == text_sha, f"{what}.text_sha is not the sha of its text")
    if spans is not None:
        _need(sum(e - s for s, e in spans) == len(text), f"{what}: the text is not the join of its spans")
    if nonblank:
        _need(bool(text.strip()), f"a {what} is never blank (design 2.0, re-review item 7)")


