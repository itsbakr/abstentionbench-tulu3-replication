class Edit(_Frozen):
    """A C pool item's edit (design 2.2): the original, the edited text and the span of the original that was
    edited. Every line of the original outside the span must survive in the edited text, in order (N10)."""

    original: str
    edited: str
    edited_span: tuple[int, int]

    @model_validator(mode="after")
    def _untouched_lines_survive(self) -> Edit:
        s, e = self.edited_span
        _need(0 <= s <= e <= len(self.original), "edited_span lies outside the original")
        kept, pos = [], 0
        for line in self.original.splitlines(keepends=True):
            ls, le = pos, pos + len(line)
            pos = le
            if not (ls < e and s < le) and not (s == e and ls <= s < le):
                kept.append(line.rstrip("\r\n"))
        edited_lines = iter(self.edited.splitlines())
        for line in kept:  # an ordered subsequence: each kept line is found after the previous one
            _need(any(x == line for x in edited_lines), f"untouched line lost by the edit: {line[:80]!r}")
        return self


