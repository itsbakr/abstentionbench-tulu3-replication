class RewardSpec(_Frozen):
    """One arm's reward of experiment C as a projection of the evaluation ScoreRecord (design section 6, step 5; OD-4,
    D9, D21). ``reward_rule`` is a ``reward_rule:`` grant of the decisions note (D9's step 2a id for the stored
    pilots, D21's post-2d id for the relaunch) and ``scorer`` the evaluation scorer's stamp under that rule, so the
    reward and the evaluation read one rule through one scorer. A record earns 1.0 when its label is in ``pays``, or,
    with ``pays_original_key``, when it is an unsolvable item whose ``detail.matches_original_key`` is True (arm a': a
    projection on the record, never a re-score under a substituted gold; review item 12). Every other record earns 0.0.
    ``no_answer`` is what an undelivered completion earns; the validator refuses any value but 0.0, and a ``pays`` that
    holds no_answer or unparsed (step 5: "no_answer earns 0 in every arm")."""

    name: str
    version: str
    arm: Literal["a", "a0", "b", "ap"]
    reward_rule: str
    scorer: ScorerId
    pays: frozenset[str]
    pays_original_key: bool
    no_answer: float

    @model_validator(mode="after")
    def _invariants(self) -> RewardSpec:
        _need(bool(re.fullmatch(r"v\d+(?:\.\d+)*", self.version)), f"version {self.version!r} is not v<n>[.<n>]")
        _need(self.reward_rule in active_registry().decisions.reward_rules,
              f"{self.reward_rule!r} is not a reward_rule grant of the decisions note (D9, D21)")
        _need(self.scorer.read_rule == self.reward_rule, "the reward reads its scorer under the reward rule (OD-4)")
        _need(self.no_answer == 0.0, "an undelivered completion earns 0 in every arm (design step 5)")
        _need(not self.pays & _NA_UP, "no arm pays no_answer or unparsed")
        _need(self.pays <= _RM_LABELS, f"pays names labels outside ReliableMath's: {sorted(self.pays - _RM_LABELS)}")
        return self

    def reward(self, record: ScoreRecord) -> float:
        """The arm's reward for one evaluation ScoreRecord; ValueError for a record another scorer or rule wrote."""
        _need(record.scorer == self.scorer, f"{record.scorer.stamp} under {record.scorer.read_rule} is not this "
                                            f"reward's scorer ({self.scorer.stamp} under {self.reward_rule})")
        _need(record.family in RELIABLEMATH_GROUP, f"the C reward reads ReliableMath records, not {record.family}")
        if record.label == "no_answer":
            return self.no_answer
        if record.label in self.pays:
            return 1.0
        if self.pays_original_key and record.detail["solvable"] is False:
            return 1.0 if record.detail["matches_original_key"] is True else 0.0
        return 0.0


