class ReportTable(_Sealed):
    """A table (design 2.7): every primary cell and delta under the one rule id ``rule_id`` (the registry's current
    primary rule once a step has run; a training run's tables under its reward's rule, which a ``reward_rule:`` grant
    must hold), every sensitivity cell's base equal to it, every registered view for every metric (budget_forced as a
    cell or as NotRun), and the clean stratum beside all for every family with item_status data (N5)."""

    ISSUER_NAME: ClassVar[str] = "report"
    rule_id: str
    cells: tuple[ReportCell | NotRun, ...]
    deltas: tuple[DeltaCell, ...]
    training_run: bool
    mac: str

    def _check_shape(self) -> None:
        reg = active_registry()
        registered_rule_d(self.rule_id)
        if self.training_run:
            _need(self.rule_id in reg.decisions.reward_rules, "a training-run table reads under a reward_rule grant")
        elif reg.current_primary_rule is not None:
            _need(self.rule_id == reg.current_primary_rule, "a table reads under the current primary rule")
        groups: dict[tuple[str, str], dict[str, set[str]]] = defaultdict(lambda: defaultdict(set))
        families: dict[str, str] = {}
        seen = set()
        for c in self.cells:
            if isinstance(c, NotRun):
                key = (c.metric_id, canonical_coordinates(c.coordinates))
                cell_key = (*key, c.item_stratum, c.view)
                families.setdefault(c.metric_id, c.metric_id.partition(".")[0])
            else:
                an = c._analysis()
                if an["column"] == "primary":
                    _need(an["read_rule"] == self.rule_id, f"a primary cell reads under {an['read_rule']}, the table "
                                                           f"under {self.rule_id}")
                else:
                    _need(an["base"] == self.rule_id, f"a sensitivity cell's base {an['base']} is not the table's rule")
                key = (c.metric.metric_id, canonical_coordinates(c.coordinates))
                cell_key = (*key, c.item_stratum, c.view)
                families[c.metric.metric_id] = c.metric.family
            _need(cell_key not in seen, f"cell {cell_key} occurs twice")
            seen.add(cell_key)
            groups[key][c.item_stratum].add(c.view)
        for d in self.deltas:
            an = d._analysis()
            for side, r in zip(("a", "b"), an["read_rules"]):
                _need(rule_base(r) == self.rule_id, f"delta side {side} reads under {r}, the table under {self.rule_id}")
        views = reg.decisions.views or CENSORING_VIEWS
        for key, strata in groups.items():
            fam = families[key[0]]
            want = {"all", "clean"} if fam in reg.families_with_item_status else {"all"}
            _need(want <= set(strata), f"{key} lacks the {sorted(want - set(strata))} stratum (N5)")
            for st, vs in strata.items():
                _need(views <= vs, f"{key} {st} lacks the views {sorted(views - vs)} (OD-3)")


# ================================================================================================== AST convention (2.0)

_RAW_KEYS = frozenset({"output", "answer", "reasoning"})
_RAW_ATTRS = frozenset({"output", "reasoning"})
_DICT_ANNOTATIONS = frozenset({"dict", "Dict", "Mapping", "MutableMapping"})
_PRIVATE_MODULES = frozenset({"withholding.typed.ingest", "withholding.typed.models"})


def _annotation_names(node: ast.AST | None) -> set[str]:
    if node is None:
        return set()
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        try:
            return _annotation_names(ast.parse(node.value, mode="eval").body)
        except SyntaxError:
            return set()
    out = set()
    for n in ast.walk(node):
        if isinstance(n, ast.Name):
            out.add(n.id)
        elif isinstance(n, ast.Attribute):
            out.add(n.attr)
    return out


def ast_violations(source: str, filename: str = "<source>") -> list[str]:
    """The "no raw text access" convention (module docstring; design 2.0) over one module's source: every line that
    reads ``output``/``answer``/``reasoning`` as a row key, ``.output``/``.reasoning`` as an attribute, takes a dict
    row, calls ``model_copy``/``model_construct`` or ``claim_issuer``, or imports or reads a private name of ingest or
    models. Returns ``file:line: what`` strings; empty when clean."""
    tree = ast.parse(source, filename)
    out: list[str] = []
    private_aliases: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and node.module:
            mod = node.module
            for a in node.names:
                if mod in _PRIVATE_MODULES and a.name.startswith("_"):
                    out.append(f"{filename}:{node.lineno}: imports the private name {a.name} of {mod}")
                if a.name == "claim_issuer":
                    out.append(f"{filename}:{node.lineno}: imports claim_issuer")
                if f"{mod}.{a.name}" in _PRIVATE_MODULES:
                    private_aliases.add(a.asname or a.name)
        elif isinstance(node, ast.Import):
            for a in node.names:
                if a.name in _PRIVATE_MODULES:
                    private_aliases.add(a.asname or a.name)
    for node in ast.walk(tree):
        if isinstance(node, ast.Subscript) and isinstance(node.slice, ast.Constant) and node.slice.value in _RAW_KEYS:
            out.append(f"{filename}:{node.lineno}: reads [{node.slice.value!r}] of a row")
        elif isinstance(node, ast.Call):
            f = node.func
            name = f.attr if isinstance(f, ast.Attribute) else f.id if isinstance(f, ast.Name) else None
            if (name == "get" and node.args and isinstance(node.args[0], ast.Constant)
                    and node.args[0].value in _RAW_KEYS):
                out.append(f"{filename}:{node.lineno}: reads .get({node.args[0].value!r}) of a row")
            if name in ("model_copy", "model_construct"):
                out.append(f"{filename}:{node.lineno}: calls {name} on a typed record")
            if name == "claim_issuer":
                out.append(f"{filename}:{node.lineno}: calls claim_issuer")
        if isinstance(node, ast.Attribute):
            if node.attr in _RAW_ATTRS:
                out.append(f"{filename}:{node.lineno}: reads .{node.attr}")
            if node.attr.startswith("_") and not node.attr.startswith("__"):
                base = node.value
                dotted = None
                if isinstance(base, ast.Name):
                    dotted = base.id
                elif isinstance(base, ast.Attribute):
                    dotted = ast.unparse(base)
                if dotted in private_aliases or dotted in _PRIVATE_MODULES:
                    out.append(f"{filename}:{node.lineno}: reads the private name {node.attr} of {dotted}")
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.Lambda)):
            args = node.args
            for a in (*args.posonlyargs, *args.args, *args.kwonlyargs, *(x for x in (args.vararg, args.kwarg) if x)):
                hit = _annotation_names(getattr(a, "annotation", None)) & _DICT_ANNOTATIONS
                if hit:
                    out.append(f"{filename}:{node.lineno}: parameter {a.arg} takes a {min(hit)} row")
    return sorted(set(out), key=lambda s: (int(s.split(":")[-2]) if s.split(":")[-2].isdigit() else 0, s))


# ================================================================================================== issuers and the self-check

_ISSUING: dict[str, tuple[str, tuple[type, ...]]] = {
    "ingest": ("withholding.typed.ingest", (DeliveredText, SensitivityText, LegacyReadText, TraceView)),
    "report": ("withholding.typed.report", (CellRow, ReportCell, DeltaCell, ReportTable)),
}


class _SelfCheckSeal(_Sealed):
    """A sealed type for the import-time self-check only: it exercises the seal every sealed type shares, without the
    registry or a completion store, so the check runs in the runner image too."""

    ISSUER_NAME: ClassVar[str] = "models (self-check)"
    key: str
    text: str
    text_sha: str
    mac: str

    def _check_shape(self) -> None:
        _check_text(self.text, self.text_sha, None, nonblank=True, what="self-check text")


def seal_self_check() -> None:
    """Design 2.0's import-time seal self-check: an issued instance verifies; a direct constructor call, model_validate
    without the issuer's token, model_construct, model_copy (with or without a new text), a field changed after issue,
    a str where an instance is expected, and an instance of a revoked issuer are each refused. ImportError otherwise."""
    issuer = _mint_issuer("self_check", (_SelfCheckSeal,))
    revoked = False
    try:
        good = issuer.issue(_SelfCheckSeal, key="k", text="t", text_sha=sha256_hex("t"))
        verify_seal(good)
        fields = {"key": "k", "text": "t", "text_sha": sha256_hex("t"), "mac": good.mac}
        tampered = issuer.issue(_SelfCheckSeal, key="k2", text="t", text_sha=sha256_hex("t"))
        object.__setattr__(tampered, "key", "k3")

        def changed() -> None:
            verify_seal(tampered)

        cases: dict[str, Callable[[], Any]] = {
            "direct constructor": lambda: _SelfCheckSeal(**fields),
            "model_validate without the issuer": lambda: _SelfCheckSeal.model_validate(fields),
            "model_construct": lambda: _SelfCheckSeal.model_construct(**fields),
            "model_copy": lambda: good.model_copy(),
            "model_copy with a new text and sha": lambda: good.model_copy(update={"text": "u",
                                                                                  "text_sha": sha256_hex("u")}),
            "a field changed after issue": changed,
            "a str where an instance is expected": lambda: verify_seal("t"),
        }
        failed = []
        for name, case in cases.items():
            try:
                case()
            except (pydantic.ValidationError, SealError):
                continue
            failed.append(name)
        issuer.revoke()
        revoked = True
        try:
            verify_seal(good)
            failed.append("an instance of a revoked issuer")
        except SealError:
            pass
    except (pydantic.ValidationError, SealError, ValueError) as e:
        raise ImportError(f"withholding.typed seal self-check could not issue: {e}") from e
    finally:
        if not revoked:
            issuer.revoke()
    if failed:
        raise ImportError(f"withholding.typed seal self-check: not refused: {failed}")
