def scorer_rule_date(name: str, version: str, read_rule: str) -> date:
    """The rule date a scorer stamp carries (design 2.5): the date of its read rule, or, for a (name, version) in
    PARSE_DECISIONS, the date of the decision that set its parse, read from that record of the active registry's
    decisions note (D20: 2026-10-17 for XSTest v1.4). ValueError when the record is missing or dated before the read
    rule."""
    rd = rule_date(read_rule)
    dec = PARSE_DECISIONS.get((name, version))
    if dec is None:
        return rd
    try:
        d = active_registry().decisions.record(dec).date
    except KeyError:
        raise ValueError(f"{name}/{version}: its parse decision {dec} is not a record of the decisions note") from None
    _need(d >= rd, f"{name}/{version}: decision {dec} ({d}) predates its read rule's date ({rd})")
    return d


class ScorerId(_Frozen):
    """A scorer stamp (design 2.5): name, version, rule date and the full registered read rule of the sealed texts it
    read, matched exactly. A (name, version) already taken under another read rule is refused, unless a grant line
    ``scorer:<name>@<version>~<read_rule>`` registers it (D16). The rule date is the read rule's, or the date of the
    decision that set the version's parse (PARSE_DECISIONS, scorer_rule_date; D20)."""

    name: str
    version: str
    rule_date: date
    read_rule: str

    @model_validator(mode="after")
    def _invariants(self) -> ScorerId:
        _need(bool(self.name) and not re.search(r"/v\d+(?:\.\d+)*$", self.name), f"name {self.name!r} holds a version")
        _need(bool(re.fullmatch(r"v\d+(?:\.\d+)*", self.version)), f"version {self.version!r} is not v<n>[.<n>]")
        registered_rule(self.read_rule)
        _need(self.rule_date == scorer_rule_date(self.name, self.version, self.read_rule),
              "rule_date is the date of the read rule, or of the decision that set the version's parse")
        reg = active_registry()
        taken = reg.taken_under(self.name, self.version)
        if taken and self.read_rule not in taken:
            _need(reg.decisions.scorer_exception(self.name, self.version, self.read_rule) is not None,
                  f"{self.stamp} is taken under {sorted(taken)}; a new reading needs a new version")
        return self

    @property
    def stamp(self) -> str:
        """``<name>/<version>`` as written into a score line."""
        return f"{self.name}/{self.version}"


