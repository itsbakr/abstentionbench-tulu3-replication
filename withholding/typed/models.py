class ThinkFacts(_Frozen):
    """The content facts of one completion's turn (design 2.3), computed by ingest from text for stored rows and from
    ids for new rows. Offsets index the raw text. The boolean flags keep co-occurring states beside the one precedence
    label (nit 21); each is checked against the facts it abbreviates."""

