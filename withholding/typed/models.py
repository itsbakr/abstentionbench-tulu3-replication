# The dependency line declared in pyproject.toml (design 2.0, step 0). The runner image has no pyproject.toml, so the
# requirement is mirrored here; tests/typed/test_models.py checks that the two agree.
PYDANTIC_REQUIREMENT = ">=2.13,<3"
_CLAUSE = re.compile(r"\s*(>=|<=|==|!=|>|<)\s*(\d+(?:\.\d+)*)\s*")


def _release(version: str) -> tuple[int, ...]:
    """The numeric release of a version string ("2.13.5" -> (2, 13, 5)); a suffix such as "rc1" is ignored."""
    m = re.match(r"\d+(?:\.\d+)*", version.strip())
    if m is None:
        raise ImportError(f"pydantic version {version!r} has no numeric release")
    return tuple(int(x) for x in m.group(0).split("."))


def _cmp(a: tuple[int, ...], b: tuple[int, ...]) -> int:
    n = max(len(a), len(b))
    a, b = a + (0,) * (n - len(a)), b + (0,) * (n - len(b))
    return (a > b) - (a < b)


def check_pydantic_version(version: str | None = None, requirement: str = PYDANTIC_REQUIREMENT) -> str:
    """Raise ImportError unless ``version`` (default: the installed pydantic) satisfies ``requirement``, a
    comma-separated list of ``>=``, ``>``, ``<=``, ``<``, ``==`` and ``!=`` clauses on release numbers. Returns the
    version checked. Run at import by ``withholding/typed/__init__.py`` (design 2.0, review item 17)."""
    v = pydantic.VERSION if version is None else version
    rel = _release(v)
    ok = {">=": lambda c: c >= 0, ">": lambda c: c > 0, "<=": lambda c: c <= 0, "<": lambda c: c < 0,
          "==": lambda c: c == 0, "!=": lambda c: c != 0}
    for clause in requirement.split(","):
        m = _CLAUSE.fullmatch(clause)
        if m is None:
            raise ImportError(f"cannot read the requirement clause {clause!r} of {requirement!r}")
        op, bound = m.groups()
        if not ok[op](_cmp(rel, _release(bound))):
            raise ImportError(f"withholding.typed needs pydantic{requirement}, found {v}")
    return v


