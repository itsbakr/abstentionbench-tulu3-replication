class Grant(_Frozen):
    """One fenced ``text`` block of a record's Registry scope (design 2.8, Revision 3), parsed line by line."""

    record: str
    rules: frozenset[str]
    reasons: frozenset[str]
    mixed_modes: frozenset[str]
    cells: frozenset[tuple[str, str]]
    deltas: frozenset[frozenset[str]]
    views: frozenset[str]
    reward_rules: frozenset[str]
    scorers: frozenset[tuple[str, str, str]]

    def holds_cell(self, metric_id: str, coordinates: Mapping[str, str]) -> bool:
        """The grant names this metric at these coordinates, or at ``any``."""
        return (metric_id, "any") in self.cells or (metric_id, canonical_coordinates(coordinates)) in self.cells


def _read_rule_line(value: str, where: str) -> str:
    try:
        rule_kind(value)
    except ValueError as e:
        raise RegistryError(f"{where}: {e}") from None
    return value


def parse_grant(record: str, lines: list[str], *, metric_ids: Mapping[str, str],
                coordinates: CoordinateScheme) -> Grant:
    """One grant from its exact strings (design 2.8): RegistryError on an unknown kind, a rule id that is not the
    canonical form of a RuleD (or of a sensitivity id over one), a ``cell:`` line naming an unregistered metric id or
    coordinate, or a ``mixed_modes:``/``cell:`` line in a grant without a sensitivity rule (or naming a rule the grant
    does not hold)."""
    k: dict[str, set] = {name: set() for name in ("rules", "reasons", "mixed_modes", "cells", "deltas", "views",
                                                  "reward_rules", "scorers")}
    mixed_lines: list[str] = []
    cell_lines: list[str] = []
    for ln in lines:
        where = f"{record}: {ln!r}"
        kind, sep, v = ln.partition(":")
        if not sep or kind not in GRANT_KINDS:
            raise RegistryError(f"{where}: unknown grant kind {kind!r}")
        if kind == "rule":
            k["rules"].add(_read_rule_line(v, where))
        elif kind == "reason":
            if v not in UNDELIVERED_REASONS:
                raise RegistryError(f"{where}: unknown undelivered reason")
            k["reasons"].add(v)
        elif kind == "mixed_modes":
            if _read_rule_line(v, where) and rule_kind(v) != "sensitivity":
                raise RegistryError(f"{where}: mixed_modes names a sensitivity id")
            k["mixed_modes"].add(v)
            mixed_lines.append(v)
        elif kind == "cell":
            metric, at, co = v.partition("@")
            if not at or metric not in metric_ids:
                raise RegistryError(f"{where}: metric id {metric!r} is not registered")
            try:
                parsed = parse_coordinates(co)
                if parsed != "any":
                    coordinates.check(parsed)
            except ValueError as e:
                raise RegistryError(f"{where}: {e}") from None
            k["cells"].add((metric, co))
            cell_lines.append(v)
        elif kind == "delta":
            a, tilde, b = v.partition("~")
            if not tilde or a == b:
                raise RegistryError(f"{where}: a delta line names two different rule ids joined by ~")
            k["deltas"].add(frozenset({_read_rule_line(a, where), _read_rule_line(b, where)}))
        elif kind == "view":
            if v not in CENSORING_VIEWS:
                raise RegistryError(f"{where}: unknown censoring view")
            k["views"].add(v)
        elif kind == "reward_rule":
            if rule_kind(_read_rule_line(v, where)) != "rule_d":
                raise RegistryError(f"{where}: a reward rule is a rule D id")
            k["reward_rules"].add(v)
        elif kind == "scorer":
            nv, tilde, rr = v.partition("~")
            name, at, ver = nv.rpartition("@")
            if not (tilde and at and name and re.fullmatch(r"v\d+(?:\.\d+)*", ver)):
                raise RegistryError(f"{where}: a scorer line is <name>@<version>~<rule id>")
            k["scorers"].add((name, ver, _read_rule_line(rr, where)))
    sens = {r for r in k["rules"] if rule_kind(r) == "sensitivity"}
    if (mixed_lines or cell_lines) and not sens:
        raise RegistryError(f"{record}: a mixed_modes: or cell: line in a grant without a sensitivity rule")
    for m in mixed_lines:
        if m not in sens:
            raise RegistryError(f"{record}: mixed_modes:{m} names a rule this grant does not register")
    return Grant(record=record, **{name: frozenset(vals) for name, vals in k.items()})


class OwnerDecisionRef(_Frozen):
    """One record of the decisions note (design 2.8): its id, date, who decided and under what authority, the adopted
    option verbatim, the section citation (heading and content sha) and the grants parsed from its own fenced blocks
    (() for a record whose Registry scope is none)."""

    id: str
    date: date
    decided_by: str
    authority: Literal["owner_decision", "adopted_recommendation"]
    text: str
    source: SectionCitation
    grants: tuple[Grant, ...]

    @model_validator(mode="after")
    def _shape(self) -> OwnerDecisionRef:
        _need(bool(re.fullmatch(r"OD-\d+|D\d+", self.id)), f"record id {self.id!r} is neither OD-n nor Dn")
        _need(self.source.heading == f"## {self.id}", "the source heading is the record id")
        _need((self.authority == "owner_decision") == self.id.startswith("OD-"),
              "OD records are the owner's decisions; D records are adopted recommendations")
        _need(all(g.record == self.id for g in self.grants), "a grant names the record it sits under")
        _need(bool(self.text.strip()), "the adopted option may not be empty")
        return self


def _record_field(body: str, label: str) -> str | None:
    m = re.search(rf"\*\*{re.escape(label)}:\*\*[ \t]*(.+)", body)
    return None if m is None else m.group(1).strip()


def parse_record(record_id: str, body: str, *, path: str, line: int, metric_ids: Mapping[str, str],
                 coordinates: CoordinateScheme) -> OwnerDecisionRef:
    """One record from the text under its heading; RegistryError when a field the registry needs is missing."""
    where = f"{path}: {record_id}"
    d = _record_field(body, "Date")
    m = re.match(r"(\d{4}-\d{2}-\d{2})", d or "")
    if m is None:
        raise RegistryError(f"{where}: no dated **Date:** line")
    authority_text = (_record_field(body, "Authority") or "").lower()
    if record_id.startswith("OD-"):
        if "owner's decision" not in authority_text:
            raise RegistryError(f"{where}: an OD record's authority is the owner's decision")
        authority = "owner_decision"
        decided = _record_field(body, "Decided by")
        decided_by = (decided or "").split(".")[0].strip()
        if decided_by != "Ahmed Bakr":
            raise RegistryError(f"{where}: decided by {decided_by!r}, not the owner")
    else:
        if "adopted" not in authority_text:
            raise RegistryError(f"{where}: a D record is adopted under the owner's delegation")
        authority, decided_by = "adopted_recommendation", "Ahmed Bakr"
    adopted = _record_field(body, "Adopted")
    if not adopted:
        raise RegistryError(f"{where}: no **Adopted:** line")
    i = body.find("**Registry scope**")
    if i < 0:
        raise RegistryError(f"{where}: no Registry scope entry")
    scope = body[i:]
    blocks = _FENCE.findall(scope)
    grants = tuple(parse_grant(record_id, [x.strip() for x in b.splitlines() if x.strip()], metric_ids=metric_ids,
                               coordinates=coordinates) for b in blocks)
    if not grants and "none" not in scope.splitlines()[0].lower():
        raise RegistryError(f"{where}: a Registry scope is 'none' with its reason, or fenced grants")
    src = SectionCitation(path=path, heading=f"## {record_id}", content_sha=section_sha(body), line_hint=line)
    return OwnerDecisionRef(id=record_id, date=date.fromisoformat(m.group(1)), decided_by=decided_by,
                            authority=authority, text=adopted, source=src, grants=grants)


class ConfirmationLine(_Frozen):
    """The owner's line in the note's Confirmation section: ``Confirmed: Ahmed Bakr, YYYY-MM-DD ...`` (design 2.8)."""

    date: date
    line: str


class RegistryPin(_Frozen):
    """What the first load after the owner's line pins: every record's content sha and the Confirmation section's sha,
    with the date of the newest confirmation line (design 2.8), and every owner's line verbatim (Revision 6), so that
    a later load can tell a line added from a line edited."""

    path: str
    confirmed_on: date
    confirmation_sha: str
    confirmation_lines: tuple[str, ...]
    record_shas: dict[str, str]


class DecisionsNote(_Frozen):
    """The OwnerDecision registry as read from the decisions note (design 2.8): the records, their grants and the
    Confirmation section. It loads whether or not the owner has signed; ``status`` says which, ``pin()`` refuses until
    the line exists, and nothing in step 0 depends on a signed note (standing rule)."""

    path: str
    records: tuple[OwnerDecisionRef, ...]
    confirmation_sha: str
    confirmations: tuple[ConfirmationLine, ...]

    @model_validator(mode="after")
    def _unique(self) -> DecisionsNote:
        ids = [r.id for r in self.records]
        _need(len(ids) == len(set(ids)), "a record id occurs once")
        return self

    @computed_field
    @property
    def status(self) -> Literal["unsigned", "confirmed"]:
        """``confirmed`` once the Confirmation section holds a line beginning ``Confirmed: Ahmed Bakr, YYYY-MM-DD``."""
        return "confirmed" if self.confirmations else "unsigned"

    @property
    def grants(self) -> tuple[Grant, ...]:
        return tuple(g for r in self.records for g in r.grants)

    def record(self, record_id: str) -> OwnerDecisionRef:
        for r in self.records:
            if r.id == record_id:
                return r
        raise KeyError(record_id)

    @property
    def rule_ids(self) -> frozenset[str]:
        """The registered read rules: every ``rule:`` line of every grant (design 2.3, 2.8)."""
        return frozenset(r for g in self.grants for r in g.rules)

    @property
    def rule_d_ids(self) -> frozenset[str]:
        return frozenset(r for r in self.rule_ids if rule_kind(r) == "rule_d")

    @property
    def sensitivity_ids(self) -> frozenset[str]:
        return frozenset(r for r in self.rule_ids if rule_kind(r) == "sensitivity")

    @property
    def reasons(self) -> frozenset[str]:
        return frozenset(x for g in self.grants for x in g.reasons)

    @property
    def views(self) -> frozenset[str]:
        return frozenset(x for g in self.grants for x in g.views)

    @property
    def reward_rules(self) -> frozenset[str]:
        return frozenset(x for g in self.grants for x in g.reward_rules)

    def grants_holding(self, rule_id: str) -> tuple[Grant, ...]:
        """The grants whose ``rule:`` lines hold exactly ``rule_id``."""
        return tuple(g for g in self.grants if rule_id in g.rules)

    def record_registering(self, rule_id: str) -> OwnerDecisionRef:
        """The one record whose grant registers ``rule_id``; RegistryError when none or several do."""
        recs = {g.record for g in self.grants_holding(rule_id)}
        if len(recs) != 1:
            raise RegistryError(f"{rule_id!r} is registered by {len(recs)} records, not one")
        return self.record(recs.pop())

    def cell_grant(self, rule_id: str, metric_id: str, coordinates: Mapping[str, str]) -> Grant | None:
        """The grant that holds ``rule:<rule_id>`` and a ``cell:`` line naming this metric at these coordinates."""
        return next((g for g in self.grants_holding(rule_id) if g.holds_cell(metric_id, coordinates)), None)

    def delta_grant(self, a: str, b: str) -> Grant | None:
        """The grant whose ``delta:`` line names exactly this unordered pair of read rules."""
        pair = frozenset({a, b})
        return next((g for g in self.grants if pair in g.deltas), None)

    def scorer_exception(self, name: str, version: str, rule_id: str) -> Grant | None:
        """The grant with the line ``scorer:<name>@<version>~<rule_id>`` (D16's kind)."""
        return next((g for g in self.grants if (name, version, rule_id) in g.scorers), None)

    def require_confirmed(self) -> None:
        """RegistryError naming the Confirmation heading while the note is unsigned (design 2.8, D11)."""
        if self.status != "confirmed":
            raise RegistryError(f"{self.path}: {CONFIRMATION_HEADING!r} holds no line beginning 'Confirmed: Ahmed "
                                f"Bakr, YYYY-MM-DD'; the registry is unsigned (D11)")

    def pin(self) -> RegistryPin:
        """Pin every record's content sha with the Confirmation section's sha (design 2.8); refused while unsigned."""
        self.require_confirmed()
        return RegistryPin(path=self.path, confirmed_on=max(c.date for c in self.confirmations),
                           confirmation_sha=self.confirmation_sha,
                           confirmation_lines=tuple(c.line for c in self.confirmations),
                           record_shas={r.id: r.source.content_sha for r in self.records})

    def check_pin(self, pin: RegistryPin) -> None:
        """RegistryError (design 2.8; Revision 6) when an owner's line the pin holds is no longer in the Confirmation
        section verbatim, whatever else was added (his lines are never edited or removed; a new dated line is added);
        or when, since the pin, a record changed, was added or was removed, or the Confirmation section changed, and
        no new confirmation line has been added. A new line is one the pin does not hold, dated on or after the pin's
        date (so the owner can confirm again the same day); with one, the caller re-pins."""
        self.require_confirmed()
        lines = {c.line for c in self.confirmations}
        gone = [ln for ln in pin.confirmation_lines if ln not in lines]
        if gone:
            raise RegistryError(f"{self.path}: {len(gone)} owner's confirmation line(s) pinned on {pin.confirmed_on} "
                                f"are no longer in {CONFIRMATION_HEADING!r} as written; a line is never edited, a new "
                                f"dated line is added")
        if any(c.line not in pin.confirmation_lines and c.date >= pin.confirmed_on for c in self.confirmations):
            return
        now = {r.id: r.source.content_sha for r in self.records}
        what = [f"records {ids} {verb}" for verb, ids in (
            ("changed", sorted(k for k in set(pin.record_shas) & set(now) if pin.record_shas[k] != now[k])),
            ("added", sorted(set(now) - set(pin.record_shas))),
            ("removed", sorted(set(pin.record_shas) - set(now)))) if ids]
        if self.confirmation_sha != pin.confirmation_sha:
            what.append(f"the {CONFIRMATION_HEADING!r} section changed")
        if what:
            raise RegistryError(f"{self.path}: {'; '.join(what)} after the pin of {pin.confirmed_on}; the owner adds a "
                                f"new dated confirmation line before they load")


def load_decisions(path: Path | str = DECISIONS_NOTE, *, text: str | None = None,
                   metric_ids: Mapping[str, str] = STEP0_METRIC_IDS,
                   coordinates: CoordinateScheme = STEP0_COORDINATES) -> DecisionsNote:
    """Read the decisions note (or ``text``, for a scratch copy) into a DecisionsNote: every ``## OD-n`` / ``## Dn``
    record, which must occur once, with its grants, and the Confirmation section. Loads unsigned; RegistryError for a
    malformed record or grant (design 2.8)."""
    p = str(path)
    src = Path(path).read_text(encoding="utf-8") if text is None else text
    sections = split_sections(src)
    heads = [h for h, _, _ in sections]
    records = []
    for h, line, body in sections:
        m = _RECORD_HEADING.fullmatch(h)
        if m is None:
            continue
        if heads.count(h) != 1:
            raise RegistryError(f"{p}: heading {h!r} occurs {heads.count(h)} times, not once")
        records.append(parse_record(m.group(1), body, path=p, line=line, metric_ids=metric_ids,
                                    coordinates=coordinates))
    if not records:
        raise RegistryError(f"{p}: no OD-n or Dn record")
    conf = resolve_heading(src, CONFIRMATION_HEADING, p)
    lines = []
    for ln in conf.splitlines():
        cm = _CONFIRMED.match(ln)
        if cm is None:
            continue
        try:
            lines.append(ConfirmationLine(date=date.fromisoformat(cm.group(1)), line=ln.rstrip()))
        except ValueError:
            raise RegistryError(f"{p}: confirmation line with an invalid date: {ln!r}") from None
    return DecisionsNote(path=p, records=tuple(records), confirmation_sha=section_sha(conf),
                         confirmations=tuple(lines))


class TakenStamp(_Frozen):
    """A scorer (name, version) already used by a stored file or a code constant, and the read rule it was written
    under: a legacy view (``legacy:<view>``) or a registered rule id (design 2.5: "step 0 lists the taken stamps")."""

    name: str
    version: str
    read_rule: str
    source: Citation

    @model_validator(mode="after")
    def _shape(self) -> TakenStamp:
        _need(bool(re.fullmatch(r"v\d+(?:\.\d+)*", self.version)), f"version {self.version!r} is not v<n>[.<n>]")
        if self.read_rule.startswith("legacy:"):
            _need(self.read_rule[7:] in LEGACY_VIEWS, f"unknown legacy view {self.read_rule!r}")
        else:
            rule_kind(self.read_rule)
        return self


