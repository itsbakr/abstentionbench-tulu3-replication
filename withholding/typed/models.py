RUN_ID = HEX16


class RunIdentity(_Frozen):
    """What a run id names (design 2.3, Revision 4): the weights (model, subfolder, revision), the TemplateSpec, the
    GenerationConfig and the draw. ``run_id`` is the first 16 hex of its canonical sha, so a completion key splits
    without ambiguity.

    ``draw`` tells two draws of one configuration apart: the output file the rows were read from, as its real path
    relative to ``results/`` (directory and file name; a directory reached through a symlink is read under its real
    path), e.g. ``tulu31/traj/step_0/outputs.jsonl``. No stored row records a seed or draw field that does it: the
    sampling seed is part of the GenerationConfig, and tulu/dpo and tulu31/traj/step_0 share seed, config and weights
    yet hold different texts. A copy of a row in another file is therefore another draw under another key; the
    same-completion relation (``same_completion_id``) says it holds the same completion."""

    model: str
    subfolder: str | None
    revision: str
    spec_id: str
    generation_config_id: str
    draw: str

    @model_validator(mode="after")
    def _draw(self) -> RunIdentity:
        _need(bool(self.draw.strip()) and self.draw == self.draw.strip() and not self.draw.startswith("/"),
              f"draw is an output file's path relative to results/, got {self.draw!r}")
        return self

    @computed_field
    @property
    def run_id(self) -> str:
        return sha256_hex(canonical_json(self.model_dump(mode="json", exclude={"run_id"})))[:16]


class CompletionKeyParts(NamedTuple):
    """The parts of a completion key (design 2.3, Revision 4), in key order."""

    run_id: str
    prompt_sha: str
    prompt_id: str
    sample: int


def completion_key(run_id: str, prompt_id: str, sample: int, *, prompt_sha: str) -> str:
    """``<run_id>/<prompt_sha>/<prompt id>#<sample>`` (design 2.3, Revision 4). Unique by construction: the run id
    hashes the draw (the output file), the prompt sha is the PromptRecord's content sha in full, and a file holds one
    row per (prompt id, sample). Both hex parts have a fixed length, so the key splits without ambiguity although
    prompt ids hold ``/``."""
    _hex(run_id, RUN_ID, "run_id")
    _hex(prompt_sha, HEX64, "prompt_sha")
    _need(isinstance(prompt_id, str) and bool(prompt_id) and "#" not in prompt_id, f"bad prompt id {prompt_id!r}")
    _need(isinstance(sample, int) and not isinstance(sample, bool) and sample >= 0, f"bad sample {sample!r}")
    return f"{run_id}/{prompt_sha}/{prompt_id}#{sample}"


def split_completion_key(key: str) -> CompletionKeyParts:
    """(run_id, prompt_sha, prompt id, sample) of a completion key; ValueError when it is not one, or not in the
    canonical form ``completion_key`` writes."""
    _need(isinstance(key, str), "a completion key is a str")
    run_id, s1, rest = key.partition("/")
    prompt_sha, s2, rest = rest.partition("/")
    prompt_id, hash_, sample = rest.rpartition("#")
    _need(bool(s1 and s2 and hash_) and bool(RUN_ID.fullmatch(run_id)) and bool(HEX64.fullmatch(prompt_sha))
          and bool(prompt_id) and "#" not in prompt_id and sample.isdigit() and str(int(sample)) == sample,
          f"not a completion key: {key!r}")
    return CompletionKeyParts(run_id, prompt_sha, prompt_id, int(sample))


def same_completion_id(run: RunIdentity, key: str, raw_sha: str) -> str:
    """The same-completion relation (design 2.3, Revision 4): two completion keys hold one completion when one set of
    weights (model, subfolder, revision) under one TemplateSpec gave the same raw text for the same prompt (prompt id
    and prompt sha) and sample. The draw and the generation config are left out, so a row copied into another file
    (think_ext carries think's first-pass rows, the recognition directories copy eval rows) and a merged extension row
    beside the outputs_ext.jsonl row it was copied from are recognised as one completion. It is text equality: it
    cannot tell a copy from an independent draw of the same weights that wrote the same text. The full sha256 hex of
    the canonical JSON of those fields; ValueError when the key is not ``run``'s."""
    parts = split_completion_key(key)
    _need(parts.run_id == run.run_id, "the key is not this run's")
    _hex(raw_sha, HEX64, "raw_sha")
    return sha256_hex(canonical_json({"model": run.model, "subfolder": run.subfolder, "revision": run.revision,
                                      "spec_id": run.spec_id, "prompt_id": parts.prompt_id,
                                      "prompt_sha": parts.prompt_sha, "sample": parts.sample, "raw_sha": raw_sha}))


