"""The typed ingestion layer's models (notes/typed_ingestion_design_2026-10-15.md, cited "design N"; the decisions in
notes/typed_layer_decisions_2026-10-15.md, cited "decisions").

Step 0: types only. Nothing here reads a stored output, writes a score or changes a number. The other modules of the
package build on these types (design 2, "Proposed module"): registry.py (TemplateSpec entries and probes), legacy.py
(the frozen 14 Oct reading), ingest.py (classification, delivery, the issuer of sealed texts) and report.py (the issuer
of cells).

Conventions (design 2.0)
------------------------
* Every model is ``frozen=True, extra="forbid", strict=True``: unknown fields fail, coercion is off (a list is not a
  tuple, a set is not a frozenset, a string is not a date, a bool is not an int). Computed fields are
  ``computed_field`` properties, so passing one at construction is an extra field and fails.
* Rule ids are computed from a typed ``RuleD`` and matched exactly against the registered set read from the decisions
  note's grants (design 2.3, 2.8); a prefix or a substring never matches.
* ``None`` means "not scored"; a no_answer or an unparsed row is valued by the report view, never by a scorer.
* No constants and no hidden cut-offs: every rule here is content-defined. A threshold (the SESOI) is a registered
  prereg parameter carried with its citation (``PreregRule``); report code holds none.

The seal (design 2.0, 2.4, 2.7)
-------------------------------
* Sealed classes: ``DeliveredText``, ``SensitivityText``, ``LegacyReadText``, ``TraceView`` (issued by
  ``withholding.typed.ingest``) and ``CellRow``, ``ReportCell``, ``DeltaCell``, ``ReportTable`` (issued by
  ``withholding.typed.report``).
* The issuing module calls ``claim_issuer("ingest", instance_check=...)`` (or ``"report"``) once, at its import.
  ``claim_issuer`` refuses any caller module other than ``withholding.typed.<name>`` and a second claim in one
  process. The ``Issuer`` it returns holds the HMAC key, generated by that call (so per process, when the issuing
  module is imported) and never stored, and the validation-context token. ``Issuer.issue(cls, **fields)`` computes the
  MAC over every declared field except ``text`` and ``mac`` (the text is bound through ``text_sha``) and validates
  under the token. Sidecars hold offsets only; ingest re-issues from the Completion store.
* Refused: a direct constructor call and ``model_validate`` without an authorised token (a ``mode="before"``
  validator), ``model_construct`` and ``model_copy`` (overridden to raise), a str or a dict where a sealed instance is
  expected, and any instance whose fields no longer match its MAC. Pydantic re-runs a model's after-validator whenever
  an instance is passed as a field value or to a ``Delivered`` argument, so a nested sealed instance is re-verified
  every time it is used: its MAC under a live issuer, its own shape checks, and the issuer's instance check (ingest's:
  the text is its completion's raw text over its offsets, and re-running delivery under the text's rule id and family
  gives the same spans and mode). ``verify_seal`` runs the same checks on demand.
* The types stop accidents and the AST test catches deliberate subversion. Python cannot hide a key from a determined
  caller, so neither is a security boundary (design 2.0).

"No raw text access", the AST-checkable convention (design 2.0)
----------------------------------------------------------------
A scorer, judge-input or reward module must not read ``output``, ``answer`` or ``reasoning`` as a key of a row
(``r["output"]``, ``r.get("answer")``); must not read ``.output`` or ``.reasoning`` as an attribute; must not take a
dict row (a parameter annotated ``dict``, ``Dict``, ``Mapping`` or ``MutableMapping``); must not call ``model_copy`` or
``model_construct``; must not import or read a private name of ``withholding.typed.ingest`` or
``withholding.typed.models``; and must not call ``claim_issuer``. ``ast_violations(source)`` implements the check and
the step 6 test runs it over the scorer, judge and reward modules. ``.answer`` as an attribute is allowed, because the
typed golds of MATH-500 and RLCR carry an ``answer`` field (design 2.2); a raw row is a dict, so its ``answer`` is a
key and is refused.

Import checks (design 2.0, review item 17): ``withholding/typed/__init__.py`` calls ``check_pydantic_version()`` and
``seal_self_check()``; either raises ``ImportError`` before anything scores.
"""
