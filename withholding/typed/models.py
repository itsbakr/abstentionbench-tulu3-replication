    def _consistent(self) -> ThinkFacts:
        n, ob = self.n_close_in_turn, self.opened_by
        _need((self.first_close_at is None) == (n == 0) == (self.last_close_at is None),
              "first_close_at and last_close_at are set exactly when the turn has a close")
        if n:
            _need(0 <= self.first_close_at <= self.last_close_at, "first_close_at <= last_close_at")
            _need((n == 1) == (self.first_close_at == self.last_close_at), "one close marker has one offset")
        _need(self.has_turn_boundary == (self.turn_boundary_at is not None), "has_turn_boundary abbreviates "
                                                                             "turn_boundary_at")
        _need(self.forced_open == (ob == "template"), "forced_open abbreviates opened_by == template")
        _need(self.unclosed == (ob is not None and n == 0), "unclosed: a block was opened and the turn has no close")
        _need(self.multiple_close == (ob is not None and n >= 2), "multiple_close: opened, two or more closes")
        _need(self.stray_close == (ob is None and n >= 1), "stray_close: no opener and a close")
        _need(self.inner_open_unclosed == (self.inner_open_at is not None), "inner_open_unclosed abbreviates "
                                                                            "inner_open_at")
        _need(self.inner_block_closed == bool(self.inner_blocks), "inner_block_closed abbreviates inner_blocks")
        _need(not (self.prefix_closed and ob == "template"), "a prefix cannot both open the block and hold a closed one")
        _need((self.close_after_odd_fence or self.close_quotes_format) <= (n > 0),
              "the fence and format facts describe the first close")
